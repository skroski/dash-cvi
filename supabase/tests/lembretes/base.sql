-- Módulo de lembretes de agendamentos + histórico de envios do n8n.
-- O dashboard gerencia as regras. O n8n usa uma credencial Supabase segura
-- (preferencialmente service_role) para consultar regras e registrar envios.

create table if not exists public.lembrete_configuracoes (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  ativo boolean not null default true,
  dias_antecedencia smallint not null default 1 check (dias_antecedencia = 1),
  horario_envio time without time zone not null default '18:00',
  timezone text not null default 'America/Sao_Paulo',
  mensagem_template text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.lembrete_envios (
  id bigint generated by default as identity primary key,
  configuracao_id bigint references public.lembrete_configuracoes(id) on delete set null,
  configuracao_nome text not null,
  agendamento_chave text not null,
  data_agendada date not null,
  horario_agendado time without time zone,
  servico text,
  nome_tutor text not null,
  nome_pet text,
  telefone text not null,
  programado_para timestamptz not null,
  status text not null default 'pendente'
    check (status in ('pendente', 'processando', 'enviado', 'falha', 'ignorado')),
  tentativas smallint not null default 0 check (tentativas >= 0),
  provider_message_id text,
  erro text,
  enviado_em timestamptz,
  descricao text,
  email text,
  porte text,
  preco numeric(12, 2),
  status_agendamento text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (configuracao_id, agendamento_chave, data_agendada)
);

create index if not exists lembrete_configuracoes_ativo_horario_idx
  on public.lembrete_configuracoes (ativo, horario_envio);
create index if not exists lembrete_envios_status_idx
  on public.lembrete_envios (status);
create index if not exists lembrete_envios_created_at_idx
  on public.lembrete_envios (created_at desc);
create index if not exists lembrete_envios_data_agendada_idx
  on public.lembrete_envios (data_agendada);

create or replace function public.set_lembrete_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_lembrete_configuracoes_updated_at
  on public.lembrete_configuracoes;
create trigger set_lembrete_configuracoes_updated_at
before update on public.lembrete_configuracoes
for each row execute function public.set_lembrete_updated_at();

drop trigger if exists set_lembrete_envios_updated_at
  on public.lembrete_envios;
create trigger set_lembrete_envios_updated_at
before update on public.lembrete_envios
for each row execute function public.set_lembrete_updated_at();

alter table public.lembrete_configuracoes enable row level security;
alter table public.lembrete_envios enable row level security;

-- Usuários autenticados do dashboard gerenciam apenas as configurações.
drop policy if exists "dashboard gerencia lembrete_configuracoes"
  on public.lembrete_configuracoes;
create policy "dashboard gerencia lembrete_configuracoes"
  on public.lembrete_configuracoes
  for all
  to authenticated
  using (true)
  with check (true);

-- O dashboard consulta o histórico. Escritas ficam a cargo do n8n com service_role.
drop policy if exists "dashboard consulta lembrete_envios"
  on public.lembrete_envios;
create policy "dashboard consulta lembrete_envios"
  on public.lembrete_envios
  for select
  to authenticated
  using (true);

grant select, insert, update, delete on public.lembrete_configuracoes to authenticated;
grant usage, select on sequence public.lembrete_configuracoes_id_seq to authenticated;
grant select on public.lembrete_envios to authenticated;
grant all on public.lembrete_configuracoes, public.lembrete_envios to service_role;
grant usage, select on sequence public.lembrete_configuracoes_id_seq,
  public.lembrete_envios_id_seq to service_role;

do $$
begin
  alter publication supabase_realtime add table public.lembrete_configuracoes;
exception
  when duplicate_object then null;
end $$;

do $$
begin
  alter publication supabase_realtime add table public.lembrete_envios;
exception
  when duplicate_object then null;
end $$;

