await caso('T8: Commit com internação e falha na internação (transacional) -> faz rollback do prontuário e mantém draft como ready', async () => {
  const draft2 = await como(VET, () =>
    one(
      `insert into public.prontuario_ia_drafts (pet_id, prontuario_id, audio_anexo_id, audio_path, status)
       values ($1, $2, 'a-audio-2', 'pet/rec/audio2.webm', 'ready')
       returning id`,
      [petId, recordId]
    )
  );

  // Envia um evento de internação com tipo inválido ('cirurgia_invalida') que viola a constraint de internacao_eventos
  const payloadInvalido = {
    diagnostico: {
      diagnostico_definitivo: 'DIAGNOSTICO QUE NAO PODE SER SALVO POR CAUSA DO ROLLBACK',
    },
    internacao: {
      motivo: 'Teste transacional',
      eventos: [
        {
          tipo: 'tipo_inexistente_que_dispara_erro',
          descricao: 'Deve falhar na constraint',
        },
      ],
    },
  };

  let falhou = false;
  try {
    await como(VET, () =>
      one(
        `select public.confirmar_prontuario_ia(
          p_pet_id => $1,
          p_record_id => $2,
          p_draft_id => $3,
          p_edited => $4::jsonb,
          p_hash_sha256 => 'hash_nao_salvo'
        )`,
        [petId, recordId, draft2.id, JSON.stringify(payloadInvalido)]
      )
    );
  } catch {
    falhou = true;
  }
  nodeAssert.equal(falhou, true, 'A chamada deve lançar erro ao falhar na internação');

  // Verifica que o prontuário NÃO foi alterado (permanece 'Gastroenterite hemorrágica')
  const recPreservado = await como(VET, () => one(`select diagnostico_definitivo from public.prontuarios where id = $1`, [recordId]));
  nodeAssert.equal(recPreservado.diagnostico_definitivo, 'Gastroenterite hemorrágica');

  // Verifica que o draft2 NÃO foi marcado como committed (continua 'ready')
  const draftPreservado = await como(VET, () => one(`select status from public.prontuario_ia_drafts where id = $1`, [draft2.id]));
  nodeAssert.equal(draftPreservado.status, 'ready');
});

await caso('T10: Leitura de prontuarios / prontuario_ia_drafts / internacoes sem login (anon) ou pelo papel totem é negada', async () => {
  // Papel anon: revogado (lança permission denied)
  for (const tabela of ['prontuarios', 'prontuario_ia_drafts', 'internacoes', 'internacao_eventos', 'prontuario_ia_config']) {
    let negadoAnon = false;
    try {
      const rows = await como('', () => q(`select * from public.${tabela}`), 'anon');
      if (rows.length === 0) negadoAnon = true;
    } catch {
      negadoAnon = true;
    }
    nodeAssert.equal(negadoAnon, true, `Acesso anon à tabela ${tabela} deve ser negado`);
  }

  // Papel totem: RLS bloqueia (0 linhas)
  const rowsTotemPront = await como(TOTEM, () => q(`select * from public.prontuarios`));
  const rowsTotemDrafts = await como(TOTEM, () => q(`select * from public.prontuario_ia_drafts`));
  nodeAssert.equal(rowsTotemPront.length, 0, 'Totem não pode ler prontuarios');
  nodeAssert.equal(rowsTotemDrafts.length, 0, 'Totem não pode ler prontuario_ia_drafts');
});

