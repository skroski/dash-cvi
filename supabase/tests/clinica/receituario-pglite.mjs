await caso('papel totem e usuários anônimos não leem nem gravam nas tabelas do receituário', async () => {
  await como(TOTEM, async () => {
    nodeAssert.equal((await q('select * from public.receituario_pacientes')).length, 0);
    nodeAssert.equal((await q('select * from public.receituario_prescricoes')).length, 0);
    nodeAssert.equal((await q('select * from public.receituario_bulario')).length, 0);
    let bloqueou = false;
    try {
      await one(`select * from public.salvar_paciente_receituario(p_tutor_nome => 'X', p_nome => 'Y', p_peso_kg => 5)`);
    } catch {
      bloqueou = true;
    }
    nodeAssert.equal(bloqueou, true, 'Totem não pode chamar salvar_paciente_receituario');
  });

  await como('', async () => {
    let bloqueou = false;
    try {
      await q('select * from public.receituario_prescricoes');
    } catch {
      bloqueou = true;
    }
    nodeAssert.equal(bloqueou, true, 'Anon não tem SELECT direto em receituario_prescricoes');
  }, 'anon');
});

