export async function criarBanco({ migracoes = MIGRACOES } = {}) {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    grant usage on schema public to anon, authenticated, service_role;
    alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
    alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
    alter default privileges in schema public grant all on functions to anon, authenticated, service_role;
    create schema auth;
    create table auth.users (id uuid primary key, email text);
    grant usage on schema auth to anon, authenticated, service_role;
    create function auth.uid() returns uuid language sql stable as
      $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    grant execute on function auth.uid() to anon, authenticated, service_role;
    create table public.profiles (id uuid primary key references auth.users(id), nome text, email text,
      papel text not null default 'atendente' check (papel in ('admin','lider','atendente')), ativo boolean not null default true);
    insert into auth.users values ('${ADMIN}', 'admin@teste.com'), ('${ATENDENTE}', 'atendente@teste.com'), ('${LIDER}', 'lider@teste.com');
    insert into public.profiles (id, nome, papel) values ('${ADMIN}', 'Admin Teste', 'admin'), ('${ATENDENTE}', 'Atendente', 'atendente'), ('${LIDER}', 'Líder', 'lider');
    create function public.sou_admin() returns boolean language sql stable security definer as
      $$ select coalesce((select papel = 'admin' from public.profiles where id = auth.uid() and ativo), false) $$;
    create function public.sou_gestor() returns boolean language sql stable security definer as
      $$ select coalesce((select papel in ('admin','lider') from public.profiles where id = auth.uid() and ativo), false) $$;
    create schema vault;
    create table vault.secrets (id uuid primary key default gen_random_uuid(), name text unique, secret text, description text, updated_at timestamptz);
    create view vault.decrypted_secrets as select id, name, secret as decrypted_secret from vault.secrets;
    create function vault.create_secret(s text, n text, d text default null) returns uuid language sql as
      $$ insert into vault.secrets (name, secret, description) values (n, s, d) returning id $$;
    -- Tabelas de migrações anteriores das quais as novas dependem.
    create table public.atendentes (id bigint generated by default as identity primary key, nome text);
    create table public.departamentos (id bigint generated by default as identity primary key, nome text not null);
    create table public.atendimento_conversas (session_id text primary key);
    create table public.tags (id bigint generated by default as identity primary key, nome text not null unique, cor text default '#0d9488');
    create table public.meu_prompt_versoes (id uuid primary key default gen_random_uuid(),
      conteudo text not null check (char_length(conteudo) between 1 and 50000), versao integer not null unique,
      criado_por uuid references auth.users(id), criado_em timestamptz not null default now());
  `);
  for (const arquivo of migracoes) await db.exec(ler(`migrations/${arquivo}`));
  return db;
}

export function ferramentas(db) {
  const q = async (sql, params) => (await db.query(sql, params)).rows;
  const one = async (sql, params) => (await q(sql, params))[0];
  async function como(uid, fn, papel = 'authenticated') {
    await db.exec(`set role ${papel}; select set_config('request.jwt.claim.sub', '${uid ?? ''}', false);`);
    try { return await fn(); } finally { await db.exec(`reset role; select set_config('request.jwt.claim.sub', '', false);`); }
  }
  async function esperaErro(fn, trecho) {
    try { await fn(); } catch (e) {
      if (trecho && !e.message.includes(trecho)) throw new Error(`erro inesperado: ${e.message}`);
      return e.message;
    }
    throw new Error('esperava erro e não houve');
  }
  let ok = 0;
  let falhas = 0;
  async function caso(nome, fn) {
    try { await fn(); ok++; console.log('  ✓', nome); } catch (e) { falhas++; console.log('  ✗', nome, '\n     ', e.message); }
  }
  return {
    q, one, como, esperaErro, caso, assert,
    comoAdmin: (fn) => como(ADMIN, fn),
    comoAtendente: (fn) => como(ATENDENTE, fn),
    comoLider: (fn) => como(LIDER, fn),
    resumo() { console.log(`\n${ok} ok, ${falhas} falha(s)`); process.exit(falhas ? 1 : 0); },
  };
}
