-- Histórico de mudanças de status das conversas (append-only).
-- Rodar no SQL Editor do Supabase (projeto napeofeenweerjhqucua), depois de
-- 20260717100000_status_conversas.sql.
--
-- PROBLEMA QUE RESOLVE: `conversas_status` tem UMA linha por sessão, então
-- `fechada_em` é sobrescrito a cada novo fechamento. Duas consequências para as
-- métricas:
--   1. a mesma conversa fechada 3x no período conta 1;
--   2. uma conversa fechada dentro do período e fechada de novo DEPOIS perde a
--      data antiga — o total de um período passado encolhe com o tempo.
-- Além disso não havia registro de QUEM fechou, o que impedia qualquer recorte
-- por usuário.
--
-- Esta tabela guarda um evento por transição, com o ator resolvido no banco
-- (auth.uid()), nunca vindo do navegador — mesmo princípio da trilha de
-- auditoria (20260725110000_auditoria.sql). Não depende das migrações de
-- perfis/papéis: se `public.profiles` ainda não existir, o nome do ator cai
-- para o e-mail do login.
--
-- COMO CONFERIR depois de rodar: feche uma conversa no painel e rode
--   select acao, ator_nome, ocorrido_em
--     from public.conversas_status_eventos
--    where ocorrido_em > now() - interval '1 day'
--    order by id desc;
-- A trigger engole os próprios erros de propósito (mudar o status da conversa
-- nunca pode falhar), então uma tabela que não cresce é o único sintoma.

-- ---------------------------------------------------------------------------
-- 1. Tabela
-- ---------------------------------------------------------------------------

create table if not exists public.conversas_status_eventos (
  id bigint generated by default as identity primary key,
  session_id text not null,
  -- Status que a conversa passou a ter. 'aberta' cobre tanto a reabertura
  -- manual quanto a automática (trigger de mensagem do cliente).
  acao text not null check (acao in ('aberta', 'fechada', 'arquivada')),
  de_status text,
  -- Momento da transição. Espelha fechada_em/arquivada_em/reaberta_em para que
  -- a métrica use a mesma data que a UI mostra na conversa.
  ocorrido_em timestamptz not null default now(),
  -- Ator: nulo quando a mudança veio do n8n/trigger automático (sistema).
  ator_user_id uuid,
  ator_atendente_id bigint,
  ator_nome text,
  created_at timestamptz not null default now()
);

-- Sem FK para conversas_status/atendentes de propósito: o histórico precisa
-- sobreviver à remoção da linha de status ou do cadastro do atendente.

create index if not exists conversas_status_eventos_ocorrido_idx
  on public.conversas_status_eventos (ocorrido_em desc);
create index if not exists conversas_status_eventos_acao_idx
  on public.conversas_status_eventos (acao, ocorrido_em desc);
create index if not exists conversas_status_eventos_session_idx
  on public.conversas_status_eventos (session_id, ocorrido_em desc);

comment on table public.conversas_status_eventos is
  'Histórico append-only das transições de status das conversas. Escrito apenas pela trigger em conversas_status.';

-- ---------------------------------------------------------------------------
-- 2. Trigger de registro
-- ---------------------------------------------------------------------------
-- `security definer` porque `authenticated` não tem INSERT nesta tabela: a
-- trigger é o único caminho de escrita. O ator sai de auth.uid(), então o
-- cliente não escolhe em nome de quem o evento é gravado.

create or replace function public.registrar_evento_status_conversa()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_atendente_id bigint;
  v_nome text;
  v_mudou boolean;
  v_ocorrido timestamptz;
begin
  if tg_op = 'UPDATE' then
    -- Fechar de novo uma conversa já fechada é um evento novo (a data muda),
    -- mas um UPDATE que só mexe em updated_at não é.
    v_mudou :=
      new.status is distinct from old.status
      or (new.status = 'fechada' and new.fechada_em is distinct from old.fechada_em)
      or (new.status = 'arquivada' and new.arquivada_em is distinct from old.arquivada_em)
      or (new.status = 'aberta' and new.reaberta_em is distinct from old.reaberta_em);

    if not v_mudou then
      return new;
    end if;
  end if;

  v_ocorrido := coalesce(
    case new.status
      when 'fechada' then new.fechada_em
      when 'arquivada' then new.arquivada_em
      else new.reaberta_em
    end,
    now()
  );

  -- Nome do ator: `profiles` pode não existir ainda (migrações 20260725*
  -- pendentes), então a resolução é tolerante e cai para o e-mail do login.
  begin
    select p.atendente_id, coalesce(a.nome, p.nome)
      into v_atendente_id, v_nome
      from public.profiles p
      left join public.atendentes a on a.id = p.atendente_id
     where p.id = v_user_id;
  exception
    when others then
      v_atendente_id := null;
      v_nome := null;
  end;

  if v_nome is null and v_user_id is not null then
    select u.email into v_nome from auth.users u where u.id = v_user_id;
  end if;

  insert into public.conversas_status_eventos (
    session_id, acao, de_status, ocorrido_em,
    ator_user_id, ator_atendente_id, ator_nome
  ) values (
    new.session_id,
    new.status,
    case when tg_op = 'UPDATE' then old.status else null end,
    v_ocorrido,
    v_user_id, v_atendente_id, v_nome
  );

  return new;
exception
  when others then
    -- Mudar o status da conversa nunca pode falhar por causa do histórico.
    return new;
end;
$$;

drop trigger if exists registrar_evento_status_conversa_trg on public.conversas_status;
create trigger registrar_evento_status_conversa_trg
  after insert or update on public.conversas_status
  for each row execute function public.registrar_evento_status_conversa();

-- ---------------------------------------------------------------------------
-- 3. Semente do histórico já existente
-- ---------------------------------------------------------------------------
-- As datas que sobreviveram em conversas_status viram eventos SEM ator (não há
-- como saber quem fechou antes desta migração). O painel atribui esses casos
-- ao atendente do atendimento da sessão; sem atendimento, entram em
-- "Sem atribuição".
--
-- As guardas protegem contra DUPLICAR, não garantem completude: se a tabela já
-- tiver qualquer evento (inclusive escrito pela trigger), a semente é pulada
-- inteira. Reexecutar a migração é seguro, mas só a primeira execução semeia.

insert into public.conversas_status_eventos (session_id, acao, ocorrido_em, ator_nome)
select cs.session_id, 'fechada', cs.fechada_em, null
  from public.conversas_status cs
 where cs.fechada_em is not null
   and not exists (select 1 from public.conversas_status_eventos);

insert into public.conversas_status_eventos (session_id, acao, ocorrido_em, ator_nome)
select cs.session_id, 'arquivada', cs.arquivada_em, null
  from public.conversas_status cs
 where cs.arquivada_em is not null
   and not exists (
     select 1 from public.conversas_status_eventos e where e.acao = 'arquivada'
   );

-- ---------------------------------------------------------------------------
-- 4. Imutabilidade
-- ---------------------------------------------------------------------------

create or replace function public.conversas_status_eventos_imutavel()
returns trigger
language plpgsql
as $$
begin
  raise exception 'O histórico de status é append-only: % não é permitido', tg_op
    using errcode = '42501';
end;
$$;

drop trigger if exists conversas_status_eventos_sem_update on public.conversas_status_eventos;
create trigger conversas_status_eventos_sem_update
  before update on public.conversas_status_eventos
  for each row execute function public.conversas_status_eventos_imutavel();

drop trigger if exists conversas_status_eventos_sem_delete on public.conversas_status_eventos;
create trigger conversas_status_eventos_sem_delete
  before delete on public.conversas_status_eventos
  for each row execute function public.conversas_status_eventos_imutavel();

-- ---------------------------------------------------------------------------
-- 5. RLS
-- ---------------------------------------------------------------------------

alter table public.conversas_status_eventos enable row level security;

-- Leitura de equipe, mesmo modelo de atividade_diaria: quem está logado no
-- painel lê o histórico da operação. Sem policy de escrita — só a trigger.
drop policy if exists "historico status leitura equipe" on public.conversas_status_eventos;
create policy "historico status leitura equipe" on public.conversas_status_eventos
  for select
  to authenticated
  using (true);

grant select on public.conversas_status_eventos to authenticated;
revoke insert, update, delete, truncate on public.conversas_status_eventos from authenticated;
revoke all on public.conversas_status_eventos from anon;

