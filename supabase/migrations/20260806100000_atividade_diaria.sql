-- Tempo de atividade no sistema: segundos com a aba do painel visível e em
-- primeiro plano, agregados por usuário e por dia. Alimenta métricas de
-- disponibilidade estilo monitoramento de equipe remota (ex.: Hubstaff/Time
-- Doctor) na aba "Atividade" do painel de Métricas.
--
-- Independente das migrações de perfis/papéis (20260725100000_perfis_papeis.sql):
-- a chave é auth.users(id) direto, então funciona mesmo em modo "login único"
-- (setupPendente = true no AuthContext). Rodar no SQL Editor do Supabase
-- (projeto napeofeenweerjhqucua).

-- ---------------------------------------------------------------------------
-- 1. Tabela
-- ---------------------------------------------------------------------------

create table if not exists public.atividade_diaria (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  data date not null,
  segundos_ativos integer not null default 0 check (segundos_ativos >= 0),
  primeira_atividade_em timestamptz,
  ultima_atividade_em timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (usuario_id, data)
);

comment on table public.atividade_diaria is
  'Segundos com a aba do painel visível e em primeiro plano, por usuário e dia (fuso America/Sao_Paulo). Só é escrita por public.registrar_atividade().';

create index if not exists atividade_diaria_data_idx
  on public.atividade_diaria (data);

-- ---------------------------------------------------------------------------
-- 2. Escrita atômica via RPC
-- ---------------------------------------------------------------------------
-- `security definer` porque não há policy de escrita na tabela — é o único
-- caminho de gravação. A autorização vem de auth.uid() (o cliente nunca
-- escolhe de quem é o registro), e o teto de 120s barra heartbeats forjados
-- ou um relógio de cliente adiantado de inflar o total.

create or replace function public.registrar_atividade(p_segundos integer)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_hoje date := (now() at time zone 'America/Sao_Paulo')::date;
begin
  if (select auth.uid()) is null then
    raise exception 'Autenticação obrigatória' using errcode = '42501';
  end if;

  -- Teto alinhado ao intervalo do heartbeat no cliente (30s) com folga: acima
  -- disso é sinal de aba suspensa/relógio incorreto, não atividade real.
  if p_segundos is null or p_segundos <= 0 or p_segundos > 120 then
    raise exception 'Intervalo de atividade inválido: %', p_segundos using errcode = '22023';
  end if;

  insert into public.atividade_diaria as a (
    usuario_id, data, segundos_ativos, primeira_atividade_em, ultima_atividade_em
  ) values (
    (select auth.uid()), v_hoje, p_segundos, now(), now()
  )
  on conflict (usuario_id, data) do update
  set segundos_ativos = a.segundos_ativos + excluded.segundos_ativos,
      ultima_atividade_em = excluded.ultima_atividade_em,
      updated_at = now();
end;
$$;

revoke execute on function public.registrar_atividade(integer) from public, anon;
grant execute on function public.registrar_atividade(integer) to authenticated;

-- ---------------------------------------------------------------------------
-- 3. RLS
-- ---------------------------------------------------------------------------

alter table public.atividade_diaria enable row level security;

-- Leitura de equipe: mesmo modelo de acesso amplo já usado em conversas_status
-- e lembrete_envios (qualquer usuário autenticado do painel lê tudo). Se as
-- migrações de perfis/papéis já estiverem aplicadas, dá para trocar por
-- "using (public.sou_gestor() or usuario_id = (select auth.uid()))" para
-- restringir o histórico de outra pessoa a gestores.
drop policy if exists "atividade leitura equipe" on public.atividade_diaria;
create policy "atividade leitura equipe" on public.atividade_diaria
  for select
  to authenticated
  using (true);

-- Privilégios explícitos: leitura apenas. A escrita acontece dentro de
-- registrar_atividade(), que roda com o dono da tabela.
grant select on public.atividade_diaria to authenticated;
revoke insert, update, delete, truncate on public.atividade_diaria from authenticated;
revoke all on public.atividade_diaria from anon;

