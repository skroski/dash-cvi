-- Mensagens avulsas programadas pelo admin diretamente nas conversas.
-- O dashboard faz o CRUD e um fluxo automatizado com service_role consome
-- os registros vencidos através de claim_mensagens_agendadas().

create table if not exists public.mensagens_agendadas (
  id bigint generated by default as identity primary key,
  session_id text not null,
  client_id bigint,
  nome_tutor text not null,
  telefone text not null,
  mensagem text not null check (length(btrim(mensagem)) > 0),
  programado_para timestamptz not null,
  timezone text not null default 'America/Sao_Paulo',
  remetente text not null default 'cvi'
    check (remetente in ('cvi')),
  status text not null default 'pendente'
    check (status in ('pendente', 'processando', 'enviado', 'falha', 'cancelado')),
  tentativas smallint not null default 0 check (tentativas >= 0),
  provider_message_id text,
  erro text,
  enviado_em timestamptz,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists mensagens_agendadas_session_idx
  on public.mensagens_agendadas (session_id, programado_para desc);
create index if not exists mensagens_agendadas_fila_idx
  on public.mensagens_agendadas (programado_para)
  where status = 'pendente';

create or replace function public.set_mensagens_agendadas_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_mensagens_agendadas_updated_at
  on public.mensagens_agendadas;
create trigger set_mensagens_agendadas_updated_at
before update on public.mensagens_agendadas
for each row execute function public.set_mensagens_agendadas_updated_at();

alter table public.mensagens_agendadas enable row level security;

drop policy if exists "dashboard consulta mensagens agendadas"
  on public.mensagens_agendadas;
create policy "dashboard consulta mensagens agendadas"
  on public.mensagens_agendadas
  for select
  to authenticated
  using (true);

drop policy if exists "dashboard cria mensagens agendadas"
  on public.mensagens_agendadas;
create policy "dashboard cria mensagens agendadas"
  on public.mensagens_agendadas
  for insert
  to authenticated
  with check (true);

drop policy if exists "dashboard atualiza mensagens agendadas"
  on public.mensagens_agendadas;
create policy "dashboard atualiza mensagens agendadas"
  on public.mensagens_agendadas
  for update
  to authenticated
  using (true)
  with check (true);

drop policy if exists "dashboard remove mensagens agendadas"
  on public.mensagens_agendadas;
create policy "dashboard remove mensagens agendadas"
  on public.mensagens_agendadas
  for delete
  to authenticated
  using (true);

grant select, insert, update, delete on public.mensagens_agendadas to authenticated;
grant usage, select on sequence public.mensagens_agendadas_id_seq to authenticated;
grant all on public.mensagens_agendadas to service_role;
grant usage, select on sequence public.mensagens_agendadas_id_seq to service_role;

-- Retira itens vencidos da fila de forma atômica. O SKIP LOCKED evita que
-- execuções simultâneas do n8n enviem a mesma mensagem duas vezes.
create or replace function public.claim_mensagens_agendadas(p_limit integer default 50)
returns setof public.mensagens_agendadas
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with vencidas as (
    select id
    from public.mensagens_agendadas
    where status = 'pendente'
      and programado_para <= now()
    order by programado_para
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 50), 200))
  )
  update public.mensagens_agendadas as mensagem
  set
    status = 'processando',
    tentativas = mensagem.tentativas + 1,
    updated_at = now()
  from vencidas
  where mensagem.id = vencidas.id
  returning mensagem.*;
end;
$$;

revoke all on function public.claim_mensagens_agendadas(integer)
  from public, anon, authenticated;
grant execute on function public.claim_mensagens_agendadas(integer)
  to service_role;

do $$
begin
  alter publication supabase_realtime add table public.mensagens_agendadas;
exception
  when duplicate_object then null;
end $$;
