-- Catálogo e cópia permanente das mídias das conversas (Uazapi).
-- Rodar no SQL Editor do Supabase (projeto napeofeenweerjhqucua).
--
-- PROBLEMA QUE RESOLVE: hoje NENHUM arquivo que passa pelo painel tem registro
-- no banco. As consequências:
--
--   1. RECEBIDOS (laudos, exames, fotos que o cliente manda): a única cópia
--      está no servidor da Uazapi, servida pela URL que `/message/find`
--      devolve. Trocar de instância, perder o token ou a retenção do provedor
--      expirar apaga o histórico inteiro de anexos — sem aviso e sem backup.
--   2. ENVIADOS pelo painel: o arquivo vai direto do navegador para a Uazapi em
--      base64 e o chat mostra um `blob:` local. Esse blob morre no F5. O anexo
--      só reaparece quando (e se) a Uazapi devolver a mensagem no
--      `/message/find` — e `useChatMessages` só lê as 200 mensagens mais
--      recentes, então em conversa movimentada ele some de vez.
--   3. Não existe forma de responder "quais arquivos essa cliente já mandou?"
--      ou "quem enviou este laudo e quando?" — nem por SQL, nem na interface.
--
-- ESTRATÉGIA (não quebra nada do que já funciona): a `mediaUrl` que o chat
-- renderiza continua sendo a da Uazapi. Esta tabela é um CATÁLOGO paralelo, e
-- o bucket guarda uma SEGUNDA cópia dos bytes. Se a migração não rodar, todas
-- as leituras novas no cliente caem para lista vazia e o chat funciona como
-- hoje.
--
-- COMO CONFERIR depois de rodar: abra uma conversa que tenha anexo no painel e
--   select direcao, tipo, nome_arquivo, storage_path, ocorrido_em
--     from public.conversa_midias
--    order by id desc limit 20;
-- Linhas com `storage_path` nulo são as que ainda têm só o ponteiro para a
-- Uazapi — a cópia dos bytes de mídia RECEBIDA é feita pela edge function
-- `arquivar-midias` (ver docs/arquivos-conversas-uazapi.md). Mídia ENVIADA
-- pelo painel já nasce com `storage_path` preenchido.
--
-- SE A SEÇÃO 4 FALHAR POR PERMISSÃO: `storage.objects` pertence a
-- `supabase_storage_admin`, então o `create policy` de lá pode ser negado
-- dependendo dos grants do projeto. A seção 4 é a ÚLTIMA do arquivo de
-- propósito: um erro nela deixa o catálogo (seções 1–3) já criado e
-- funcionando. Nesse caso, faça o equivalente pelo Dashboard:
--   • Storage → New bucket: nome `conversa-midias`, PRIVADO, limite 20MB;
--   • Storage → Policies, no bucket `conversa-midias`: uma policy de SELECT e
--     uma de INSERT, ambas para o papel `authenticated`.
-- O `insert into storage.buckets` também pode reclamar de coluna nova em
-- versões recentes do Storage — mesmo caminho, crie o bucket pelo Dashboard.

-- ---------------------------------------------------------------------------
-- 1. Tabela
-- ---------------------------------------------------------------------------

create table if not exists public.conversa_midias (
  id bigint generated by default as identity primary key,

  -- JID da conversa como a Uazapi usa: 55DDNNNNNNNNN@s.whatsapp.net para
  -- individual, ...@g.us para grupo. É a mesma chave do `session_id` de
  -- n8n_chat_histories nas conversas individuais.
  session_id text not null,
  -- Só dígitos, para cruzar com dados_cliente.telefone. Nulo em grupos.
  telefone text,

  -- ID da mensagem na Uazapi. É o que torna a indexação idempotente: abrir a
  -- mesma conversa dez vezes não gera dez linhas. Quando o painel envia e a
  -- Uazapi não devolve um id na resposta, gravamos 'local:<uuid>' para manter
  -- a coluna NOT NULL (o upsert do PostgREST não sabe inferir índice parcial).
  message_id text not null,

  direcao text not null check (direcao in ('enviada', 'recebida')),
  tipo text not null check (tipo in ('image', 'audio', 'video', 'document', 'sticker', 'outro')),

  nome_arquivo text,
  mime_type text,
  tamanho_bytes bigint,
  -- Legenda/texto que acompanhou o anexo, já com a assinatura do atendente.
  legenda text,

  -- Ponteiro original (servidor da Uazapi). Pode expirar — é justamente por
  -- isso que existe o storage_path.
  uazapi_url text,
  -- Caminho no bucket 'conversa-midias'. Nulo = bytes ainda não copiados.
  storage_path text,
  arquivada_em timestamptz,

  -- Autoria só existe para o que sai do painel: a Uazapi não diz qual atendente
  -- apertou o botão. Nulo em mídia recebida e no que o bot/n8n envia.
  enviada_por_user_id uuid,
  enviada_por_nome text,

  -- Horário da mensagem (o mesmo que o chat mostra), não o do INSERT.
  ocorrido_em timestamptz not null default now(),
  created_at timestamptz not null default now(),

  unique (session_id, message_id)
);

comment on table public.conversa_midias is
  'Catálogo dos arquivos trocados nas conversas do WhatsApp (Uazapi). uazapi_url é o ponteiro volátil do provedor; storage_path é a cópia permanente no bucket conversa-midias.';
comment on column public.conversa_midias.message_id is
  'ID da mensagem na Uazapi, ou local:<uuid> quando o envio não devolveu id. Garante idempotência da indexação.';
comment on column public.conversa_midias.storage_path is
  'Caminho no bucket conversa-midias. Nulo enquanto os bytes só existirem no servidor da Uazapi.';

create index if not exists conversa_midias_sessao_idx
  on public.conversa_midias (session_id, ocorrido_em desc);
create index if not exists conversa_midias_telefone_idx
  on public.conversa_midias (telefone, ocorrido_em desc);
-- Fila da edge function de arquivamento: o que ainda não tem cópia dos bytes.
create index if not exists conversa_midias_pendentes_idx
  on public.conversa_midias (ocorrido_em)
  where storage_path is null and uazapi_url is not null;

-- ---------------------------------------------------------------------------
-- 2. RLS
-- ---------------------------------------------------------------------------
-- Mesmo modelo de acesso amplo de conversas_status e atividade_diaria: quem
-- está logado no painel atende qualquer conversa, então lê e cataloga qualquer
-- conversa. O que NÃO se concede é DELETE — o catálogo não pode ser esvaziado
-- pelo navegador, nem por engano nem por token vazado.

alter table public.conversa_midias enable row level security;

drop policy if exists "conversa_midias leitura equipe" on public.conversa_midias;
create policy "conversa_midias leitura equipe" on public.conversa_midias
  for select
  to authenticated
  using (true);

drop policy if exists "conversa_midias registro equipe" on public.conversa_midias;
create policy "conversa_midias registro equipe" on public.conversa_midias
  for insert
  to authenticated
  with check (true);

-- UPDATE existe só para completar o registro (storage_path/arquivada_em)
-- quando os bytes são copiados depois da indexação.
drop policy if exists "conversa_midias atualizacao equipe" on public.conversa_midias;
create policy "conversa_midias atualizacao equipe" on public.conversa_midias
  for update
  to authenticated
  using (true)
  with check (true);

grant select, insert, update on public.conversa_midias to authenticated;
-- O projeto concede ALL por default privileges; o revoke abaixo é o que de
-- fato impede o cliente de apagar o catálogo.
revoke delete, truncate on public.conversa_midias from authenticated;
revoke all on public.conversa_midias from anon;
grant usage, select on sequence public.conversa_midias_id_seq to authenticated;

-- ---------------------------------------------------------------------------
-- 3. Visão de apoio
-- ---------------------------------------------------------------------------
-- Atalho para auditoria manual no SQL Editor: "o que ainda depende só da
-- Uazapi?". Se esta consulta cresce sem parar, a edge function de
-- arquivamento não está rodando.

create or replace view public.conversa_midias_pendentes as
  select id, session_id, telefone, tipo, nome_arquivo, uazapi_url, ocorrido_em
    from public.conversa_midias
   where storage_path is null
     and uazapi_url is not null
   order by ocorrido_em desc;

comment on view public.conversa_midias_pendentes is
  'Mídias catalogadas cujos bytes ainda só existem no servidor da Uazapi.';

-- `security_invoker = on` é OBRIGATÓRIO aqui: sem isso a view roda com os
-- privilégios de quem a criou (postgres) e LÊ A TABELA IGNORANDO A RLS. Como o
-- projeto concede ALL por default privileges, `anon` passaria a enxergar
-- `uazapi_url` — link direto para laudo e exame — justamente o que o bucket
-- privado existe para impedir.
alter view public.conversa_midias_pendentes set (security_invoker = on);

revoke all on public.conversa_midias_pendentes from anon;
grant select on public.conversa_midias_pendentes to authenticated;

-- ---------------------------------------------------------------------------
-- 4. Bucket de armazenamento
-- ---------------------------------------------------------------------------
-- ÚLTIMA seção de propósito: é a única que depende de privilégio sobre um
-- schema que não é nosso (`storage`). Se falhar, tudo acima já está aplicado —
-- ver a nota no cabeçalho para o caminho pelo Dashboard.
--
-- PRIVADO de propósito: são laudos, exames e fotos de pacientes. O acesso sai
-- sempre por URL assinada com validade curta, gerada para quem está logado.
-- Teto de 20MB = os 15MB que o MessageInput já aceita, com folga.

insert into storage.buckets (id, name, public, file_size_limit)
values ('conversa-midias', 'conversa-midias', false, 20971520)
on conflict (id) do nothing;

drop policy if exists "conversa-midias leitura autenticada" on storage.objects;
create policy "conversa-midias leitura autenticada" on storage.objects
  for select
  to authenticated
  using (bucket_id = 'conversa-midias');

drop policy if exists "conversa-midias escrita autenticada" on storage.objects;
create policy "conversa-midias escrita autenticada" on storage.objects
  for insert
  to authenticated
  with check (bucket_id = 'conversa-midias');

-- Sem policy de UPDATE/DELETE para `authenticated`: arquivo de prontuário não
-- se sobrescreve nem se apaga pelo painel. Correções passam pelo service_role.
