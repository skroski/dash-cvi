-- Status operacional do atendente (disponível, almoço, pausa, reunião...) +
-- histórico com início e fim de cada período.
-- Depende de: 20260725100000_perfis_papeis.sql, 20260725110000_auditoria.sql
--
-- Códigos ficam em português para acompanhar a convenção do schema
-- (`atendimentos.status` = 'aberto'/'encerrado'); os rótulos da interface saem
-- de src/types/status.ts.

-- ---------------------------------------------------------------------------
-- 1. Status atual — exatamente um por atendente (garantido pela PK)
-- ---------------------------------------------------------------------------

create table if not exists public.atendente_status (
  atendente_id bigint primary key references public.atendentes(id) on delete cascade,
  status text not null default 'offline'
    check (status in ('disponivel', 'em_atendimento', 'almoco', 'pausa', 'reuniao', 'offline')),
  motivo text,
  previsao_retorno timestamptz,
  alterado_em timestamptz not null default now(),
  alterado_por uuid references auth.users(id) on delete set null
);

comment on table public.atendente_status is
  'Status operacional corrente. Só é alterado por public.definir_status_atendente().';

-- ---------------------------------------------------------------------------
-- 2. Histórico
-- ---------------------------------------------------------------------------

create table if not exists public.atendente_status_historico (
  id bigint generated by default as identity primary key,
  atendente_id bigint not null references public.atendentes(id) on delete cascade,
  status_anterior text,
  status text not null,
  motivo text,
  alterado_por uuid references auth.users(id) on delete set null,
  iniciado_em timestamptz not null default now(),
  encerrado_em timestamptz
);

-- Integridade: no máximo um período aberto por atendente (mesmo padrão do
-- índice `atendimentos_session_aberto_uidx` já usado no projeto).
create unique index if not exists atendente_status_historico_aberto_uidx
  on public.atendente_status_historico (atendente_id)
  where encerrado_em is null;

create index if not exists atendente_status_historico_atendente_idx
  on public.atendente_status_historico (atendente_id, iniciado_em desc);

-- ---------------------------------------------------------------------------
-- 3. Alteração atômica de status
-- ---------------------------------------------------------------------------
-- `security definer` porque a função precisa escrever em três tabelas que não
-- têm policy de escrita — é o único caminho de gravação, o que garante que
-- status atual, histórico e auditoria nunca fiquem fora de sincronia.
-- A autorização é feita DENTRO da função a partir de auth.uid(); o parâmetro
-- p_atendente_id nunca é aceito como verdade.

create or replace function public.definir_status_atendente(
  p_atendente_id bigint,
  p_status text,
  p_motivo text default null,
  p_previsao_retorno timestamptz default null
)
returns public.atendente_status
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_meu_atendente_id bigint := public.perfil_atendente_id();
  v_status_anterior text;
  v_existe boolean;
  v_resultado public.atendente_status;
  v_ativo boolean;
  v_motivo text := nullif(trim(coalesce(p_motivo, '')), '');
begin
  if (select auth.uid()) is null then
    raise exception 'Autenticação obrigatória' using errcode = '42501';
  end if;

  -- Só o próprio atendente ou um gestor (admin/líder) muda o status.
  if v_meu_atendente_id is distinct from p_atendente_id and not public.sou_gestor() then
    raise exception 'Sem permissão para alterar o status de outro atendente'
      using errcode = '42501';
  end if;

  if p_status not in ('disponivel', 'em_atendimento', 'almoco', 'pausa', 'reuniao', 'offline') then
    raise exception 'Status inválido: %', p_status using errcode = '22023';
  end if;

  select a.ativo into v_ativo
  from public.atendentes a
  where a.id = p_atendente_id;

  if v_ativo is null then
    raise exception 'Atendente não encontrado' using errcode = '23503';
  end if;

  if not v_ativo then
    raise exception 'Atendente inativo não pode ter status operacional'
      using errcode = '23514';
  end if;

  -- Trava a linha do status atual: duas mudanças simultâneas serializam aqui
  -- em vez de gerarem dois períodos abertos no histórico.
  select s.status into v_status_anterior
  from public.atendente_status s
  where s.atendente_id = p_atendente_id
  for update;
  v_existe := found;

  -- Mesmo status: o período não mudou, então apenas ajusta motivo/previsão sem
  -- abrir um novo registro no histórico nem duplicar evento de auditoria.
  if v_existe and v_status_anterior = p_status then
    update public.atendente_status s
    set motivo = v_motivo,
        previsao_retorno = p_previsao_retorno
    where s.atendente_id = p_atendente_id
    returning * into v_resultado;

    update public.atendente_status_historico
    set motivo = v_motivo
    where atendente_id = p_atendente_id and encerrado_em is null;

    return v_resultado;
  end if;

  update public.atendente_status_historico
  set encerrado_em = now()
  where atendente_id = p_atendente_id and encerrado_em is null;

  insert into public.atendente_status as s (
    atendente_id, status, motivo, previsao_retorno, alterado_em, alterado_por
  ) values (
    p_atendente_id, p_status, v_motivo,
    p_previsao_retorno, now(), (select auth.uid())
  )
  on conflict (atendente_id) do update
  set status = excluded.status,
      motivo = excluded.motivo,
      previsao_retorno = excluded.previsao_retorno,
      alterado_em = excluded.alterado_em,
      alterado_por = excluded.alterado_por
  returning * into v_resultado;

  insert into public.atendente_status_historico (
    atendente_id, status_anterior, status, motivo, alterado_por, iniciado_em
  ) values (
    p_atendente_id, v_status_anterior, p_status,
    v_motivo, (select auth.uid()), now()
  );

  perform public.auditoria_registrar(
    'status.alterado', 'atendente', p_atendente_id::text,
    p_atendente_id, null, null, null,
    jsonb_build_object(
      'de', v_status_anterior,
      'para', p_status,
      'previsao_retorno', p_previsao_retorno
    )
  );

  return v_resultado;
end;
$$;

revoke execute on function public.definir_status_atendente(bigint, text, text, timestamptz)
  from public, anon;
grant execute on function public.definir_status_atendente(bigint, text, text, timestamptz)
  to authenticated;

-- ---------------------------------------------------------------------------
-- 4. RLS
-- ---------------------------------------------------------------------------

alter table public.atendente_status enable row level security;
alter table public.atendente_status_historico enable row level security;

-- Quem está disponível é informação de equipe: todo usuário ativo lê.
drop policy if exists "status atual leitura" on public.atendente_status;
create policy "status atual leitura" on public.atendente_status
  for select
  to authenticated
  using (public.perfil_papel() is not null);

-- Histórico: gestor vê todos, atendente vê o próprio.
drop policy if exists "status historico leitura" on public.atendente_status_historico;
create policy "status historico leitura" on public.atendente_status_historico
  for select
  to authenticated
  using (public.sou_gestor() or atendente_id = public.perfil_atendente_id());

-- Sem policies de escrita: o único caminho é definir_status_atendente().

-- Privilégios explícitos: leitura apenas. A escrita acontece dentro da função
-- `security definer`, que roda com o dono da tabela.
grant select on public.atendente_status to authenticated;
grant select on public.atendente_status_historico to authenticated;
-- O projeto concede ALL por default privileges; o revoke abaixo é o que de fato
-- força toda escrita a passar por definir_status_atendente().
revoke insert, update, delete, truncate on public.atendente_status from authenticated;
revoke insert, update, delete, truncate on public.atendente_status_historico from authenticated;
revoke all on public.atendente_status from anon;
revoke all on public.atendente_status_historico from anon;

-- ---------------------------------------------------------------------------
-- 5. Realtime — o líder vê a equipe mudar de status ao vivo
-- ---------------------------------------------------------------------------

do $$
begin
  alter publication supabase_realtime add table public.atendente_status;
exception
  when duplicate_object then null;
end $$;

-- ---------------------------------------------------------------------------
-- 6. Estado inicial para quem já está cadastrado
-- ---------------------------------------------------------------------------

insert into public.atendente_status (atendente_id, status)
select a.id, 'offline'
from public.atendentes a
on conflict (atendente_id) do nothing;

-- Novos atendentes já nascem com status.
create or replace function public.atendente_status_inicial()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.atendente_status (atendente_id, status)
  values (new.id, 'offline')
  on conflict (atendente_id) do nothing;
  return new;
end;
$$;

drop trigger if exists atendente_status_inicial_trg on public.atendentes;
create trigger atendente_status_inicial_trg
  after insert on public.atendentes
  for each row execute function public.atendente_status_inicial();

