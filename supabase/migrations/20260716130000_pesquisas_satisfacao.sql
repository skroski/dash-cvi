-- Chamado pelo n8n antes de enviar. A primeira execução cria o destinatário e
-- devolve deve_enviar=true. Somente falhas explícitas podem ser reabertas; registros
-- pendentes, enviados ou cadastrados nunca liberam um segundo envio.
create or replace function public.preparar_envio_pesquisa_satisfacao(
  p_configuracao_id bigint,
  p_nome_tutor text,
  p_telefone text,
  p_email text default null,
  p_client_id bigint default null,
  p_agendamento_chave text default null,
  p_data_agendada date default null,
  p_horario_agendado time without time zone default null,
  p_servico text default null,
  p_nome_pet text default null
)
returns table (
  envio_id bigint,
  tracking_token uuid,
  link_pesquisa text,
  status text,
  deve_enviar boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_config public.pesquisa_satisfacao_configuracoes%rowtype;
  v_envio public.pesquisa_satisfacao_envios%rowtype;
  v_token uuid := gen_random_uuid();
  v_link text;
  v_separator text;
begin
  select *
    into v_config
    from public.pesquisa_satisfacao_configuracoes
   where id = p_configuracao_id
     and ativo = true;

  if not found then
    raise exception 'Configuração de pesquisa inexistente ou inativa';
  end if;

  select *
    into v_envio
    from public.pesquisa_satisfacao_envios
   where configuracao_id = p_configuracao_id
     and telefone_normalizado = regexp_replace(p_telefone, '[^0-9]', '', 'g')
   for update;

  if found then
    if v_envio.status = 'falha' then
      update public.pesquisa_satisfacao_envios
         set status = 'pendente',
             erro = null
       where id = v_envio.id
       returning * into v_envio;

      return query
        select v_envio.id, v_envio.tracking_token, v_envio.link_pesquisa,
          v_envio.status, true;
      return;
    end if;

    return query
      select v_envio.id, v_envio.tracking_token, v_envio.link_pesquisa,
        v_envio.status, false;
    return;
  end if;

  v_separator := case when position('?' in v_config.google_form_url) > 0
    then '&' else '?' end;
  v_link := v_config.google_form_url || v_separator || 'usp=pp_url&entry.'
    || v_config.google_token_entry_id || '=' || v_token::text;

  begin
    insert into public.pesquisa_satisfacao_envios (
      configuracao_id,
      configuracao_nome,
      client_id,
      agendamento_chave,
      data_agendada,
      horario_agendado,
      servico,
      nome_pet,
      nome_tutor,
      telefone,
      email,
      tracking_token,
      link_pesquisa
    )
    values (
      v_config.id,
      v_config.nome,
      p_client_id,
      p_agendamento_chave,
      p_data_agendada,
      p_horario_agendado,
      p_servico,
      p_nome_pet,
      p_nome_tutor,
      p_telefone,
      p_email,
      v_token,
      v_link
    )
    returning * into v_envio;
  exception when unique_violation then
    select *
      into v_envio
      from public.pesquisa_satisfacao_envios
     where configuracao_id = p_configuracao_id
       and telefone_normalizado = regexp_replace(p_telefone, '[^0-9]', '', 'g');

    return query
      select v_envio.id, v_envio.tracking_token, v_envio.link_pesquisa,
        v_envio.status, false;
    return;
  end;

  return query
    select v_envio.id, v_envio.tracking_token, v_envio.link_pesquisa,
      v_envio.status, true;
end;
$$;

-- Chamado somente pela Edge Function. O upsert torna reenvios do Google Forms
-- idempotentes e altera o destinatário para Cadastrado na mesma transação.
create or replace function public.registrar_resposta_pesquisa_satisfacao(
  p_tracking_token uuid,
  p_form_id text,
  p_google_response_id text,
  p_submitted_at timestamptz,
  p_nota numeric default null,
  p_nps smallint default null,
  p_comentario text default null,
  p_email text default null,
  p_telefone text default null,
  p_respostas jsonb default '{}'::jsonb
)
returns table (
  envio_id bigint,
  status text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_envio_id bigint;
  v_configuracao_id bigint;
begin
  select e.id, e.configuracao_id
    into v_envio_id, v_configuracao_id
    from public.pesquisa_satisfacao_envios e
    join public.pesquisa_satisfacao_configuracoes c on c.id = e.configuracao_id
   where e.tracking_token = p_tracking_token
     and c.ativo = true
     and c.google_form_id = p_form_id;

  if not found then
    raise exception 'Código de acompanhamento ou formulário inválido';
  end if;

  insert into public.pesquisa_satisfacao_respostas (
    envio_id,
    configuracao_id,
    google_response_id,
    submitted_at,
    nota,
    nps,
    comentario,
    email,
    telefone,
    respostas
  )
  values (
    v_envio_id,
    v_configuracao_id,
    nullif(p_google_response_id, ''),
    coalesce(p_submitted_at, now()),
    p_nota,
    p_nps,
    p_comentario,
    p_email,
    p_telefone,
    coalesce(p_respostas, '{}'::jsonb)
  )
  on conflict (envio_id) do update set
    google_response_id = coalesce(
      excluded.google_response_id,
      public.pesquisa_satisfacao_respostas.google_response_id
    ),
    submitted_at = excluded.submitted_at,
    nota = excluded.nota,
    nps = excluded.nps,
    comentario = excluded.comentario,
    email = excluded.email,
    telefone = excluded.telefone,
    respostas = excluded.respostas;

  update public.pesquisa_satisfacao_envios
     set status = 'cadastrado',
         cadastrado_em = coalesce(cadastrado_em, p_submitted_at, now()),
         erro = null
   where id = v_envio_id;

  return query select v_envio_id, 'cadastrado'::text;
end;
$$;

