-- Pesquisas de satisfação com deduplicação por tutor, integração Google Forms
-- e importação idempotente de respostas.

create extension if not exists pgcrypto;

create table if not exists public.pesquisa_satisfacao_configuracoes (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  ativo boolean not null default true,
  google_form_id text not null,
  google_form_url text not null,
  google_token_entry_id text not null,
  mensagem_template text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (length(trim(nome)) > 0),
  check (length(trim(google_form_id)) > 0),
  check (length(trim(google_form_url)) > 0),
  check (google_token_entry_id ~ '^[0-9]+$'),
  check (position('{{link_pesquisa}}' in mensagem_template) > 0)
);

create table if not exists public.pesquisa_satisfacao_envios (
  id bigint generated by default as identity primary key,
  configuracao_id bigint not null
    references public.pesquisa_satisfacao_configuracoes(id) on delete restrict,
  configuracao_nome text not null,
  client_id bigint,
  agendamento_chave text,
  data_agendada date,
  horario_agendado time without time zone,
  servico text,
  nome_pet text,
  nome_tutor text not null,
  telefone text not null,
  telefone_normalizado text generated always as (
    regexp_replace(telefone, '[^0-9]', '', 'g')
  ) stored,
  email text,
  status text not null default 'pendente'
    check (status in ('pendente', 'enviado', 'cadastrado', 'falha')),
  tracking_token uuid not null default gen_random_uuid() unique,
  link_pesquisa text,
  provider_message_id text,
  erro text,
  enviado_em timestamptz,
  cadastrado_em timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (length(regexp_replace(telefone, '[^0-9]', '', 'g')) >= 8),
  constraint pesquisa_satisfacao_envios_tutor_unico
    unique (configuracao_id, telefone_normalizado)
);

create table if not exists public.pesquisa_satisfacao_respostas (
  id bigint generated by default as identity primary key,
  envio_id bigint not null unique
    references public.pesquisa_satisfacao_envios(id) on delete cascade,
  configuracao_id bigint not null
    references public.pesquisa_satisfacao_configuracoes(id) on delete restrict,
  google_response_id text unique,
  submitted_at timestamptz not null,
  nota numeric(3, 2) check (nota is null or nota between 1 and 5),
  nps smallint check (nps is null or nps between 0 and 10),
  comentario text,
  email text,
  telefone text,
  respostas jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists pesquisa_satisfacao_configuracoes_ativo_idx
  on public.pesquisa_satisfacao_configuracoes (ativo);
create index if not exists pesquisa_satisfacao_envios_status_idx
  on public.pesquisa_satisfacao_envios (status);
create index if not exists pesquisa_satisfacao_envios_created_at_idx
  on public.pesquisa_satisfacao_envios (created_at desc);
create index if not exists pesquisa_satisfacao_respostas_submitted_at_idx
  on public.pesquisa_satisfacao_respostas (submitted_at desc);

