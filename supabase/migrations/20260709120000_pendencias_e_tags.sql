-- Pendências de clientes + sistema de tags reutilizáveis
-- Rodar no SQL Editor do Supabase (projeto napeofeenweerjhqucua) ou via `supabase db push`.

-- Catálogo de tipos de pendência (lista pré-preenchida, editável no dashboard)
create table if not exists public.pendencia_tipos (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  created_at timestamptz not null default now()
);

-- Pendências vinculadas a clientes (dados_cliente)
create table if not exists public.client_pendencias (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.dados_cliente(id) on delete cascade,
  tipo_id bigint references public.pendencia_tipos(id) on delete set null,
  descricao text not null,
  observacao text,
  status text not null default 'pendente' check (status in ('pendente', 'concluida')),
  created_at timestamptz not null default now(),
  concluida_em timestamptz
);

create index if not exists client_pendencias_client_id_idx on public.client_pendencias (client_id);
create index if not exists client_pendencias_status_idx on public.client_pendencias (status);

-- Tags reutilizáveis
create table if not exists public.tags (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  cor text not null default '#0d9488',
  created_at timestamptz not null default now()
);

-- Vínculo cliente <-> tag
create table if not exists public.client_tags (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.dados_cliente(id) on delete cascade,
  tag_id bigint not null references public.tags(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (client_id, tag_id)
);

create index if not exists client_tags_client_id_idx on public.client_tags (client_id);
create index if not exists client_tags_tag_id_idx on public.client_tags (tag_id);

-- O dashboard acessa o banco com a anon key (mesmo modelo das tabelas existentes),
-- então as policies liberam acesso total.
alter table public.pendencia_tipos enable row level security;
alter table public.client_pendencias enable row level security;
alter table public.tags enable row level security;
alter table public.client_tags enable row level security;

drop policy if exists "acesso total pendencia_tipos" on public.pendencia_tipos;
create policy "acesso total pendencia_tipos" on public.pendencia_tipos
  for all using (true) with check (true);

drop policy if exists "acesso total client_pendencias" on public.client_pendencias;
create policy "acesso total client_pendencias" on public.client_pendencias
  for all using (true) with check (true);

drop policy if exists "acesso total tags" on public.tags;
create policy "acesso total tags" on public.tags
  for all using (true) with check (true);

drop policy if exists "acesso total client_tags" on public.client_tags;
create policy "acesso total client_tags" on public.client_tags
  for all using (true) with check (true);

