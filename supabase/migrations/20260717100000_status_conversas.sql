-- Ciclo de vida das conversas: fechamento, arquivamento e reabertura.
-- Rodar no SQL Editor do Supabase (projeto jhzxtpmlpjmufhhbdlr).
--
-- Uma conversa sem linha nesta tabela é considerada "aberta" (estado padrão).
-- Fechar ou arquivar cria/atualiza a linha da sessão; reabrir volta o status
-- para 'aberta' preservando as datas anteriores para consulta.

create table if not exists public.conversas_status (
  id bigint generated by default as identity primary key,
  session_id text not null unique,
  status text not null default 'aberta' check (status in ('aberta', 'fechada', 'arquivada')),
  fechada_em timestamptz,
  arquivada_em timestamptz,
  reaberta_em timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists conversas_status_status_idx
  on public.conversas_status (status);

-- Mesmo modelo de acesso das demais tabelas do dashboard (anon key)
alter table public.conversas_status enable row level security;

drop policy if exists "acesso total conversas_status" on public.conversas_status;
create policy "acesso total conversas_status" on public.conversas_status
  for all using (true) with check (true);

-- Realtime: mudanças de status refletem ao vivo em todos os dashboards abertos
do $$
begin
  alter publication supabase_realtime add table public.conversas_status;
exception
  when duplicate_object then null;
end $$;
