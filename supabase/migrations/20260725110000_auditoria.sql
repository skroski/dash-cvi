-- Trilha de auditoria operacional (append-only), alimentada por triggers.
-- Depende de: 20260725100000_perfis_papeis.sql
--
-- DECISÃO DE DESIGN: a auditoria é escrita por TRIGGERS no banco, não pelo
-- frontend. Assim ela registra o que de fato aconteceu (inclusive alterações
-- feitas por fora do painel) e o cliente não tem como forjar nem omitir um
-- evento — não existe policy de INSERT para `authenticated`.

-- ---------------------------------------------------------------------------
-- 1. Tabela
-- ---------------------------------------------------------------------------

create table if not exists public.auditoria_eventos (
  id bigint generated by default as identity primary key,
  acao text not null,
  entidade text not null,
  entidade_id text,
  -- Ator: quem executou. Nulo quando a ação veio do n8n/service_role (sistema).
  ator_user_id uuid,
  ator_atendente_id bigint,
  ator_nome text,
  -- Alvo: sobre quem/o quê a ação recaiu.
  alvo_atendente_id bigint,
  alvo_user_id uuid,
  atendimento_id bigint,
  session_id text,
  -- Apenas o delta relevante, nunca a linha inteira (evita JSONB gigante e
  -- reduz o risco de guardar dado pessoal desnecessário).
  dados jsonb,
  created_at timestamptz not null default now()
);

-- Sem FK para atendimentos/atendentes de propósito: a trilha precisa sobreviver
-- à remoção do registro auditado (um `on delete cascade` apagaria a prova, e um
-- `on delete set null` violaria o caráter append-only).

create index if not exists auditoria_eventos_created_at_idx
  on public.auditoria_eventos (created_at desc);
create index if not exists auditoria_eventos_acao_idx
  on public.auditoria_eventos (acao, created_at desc);
create index if not exists auditoria_eventos_ator_idx
  on public.auditoria_eventos (ator_atendente_id, created_at desc);
create index if not exists auditoria_eventos_alvo_idx
  on public.auditoria_eventos (alvo_atendente_id, created_at desc);
create index if not exists auditoria_eventos_atendimento_idx
  on public.auditoria_eventos (atendimento_id, created_at desc);

comment on table public.auditoria_eventos is
  'Trilha append-only de ações operacionais. Escrita apenas por triggers/funções security definer.';

-- ---------------------------------------------------------------------------
-- 2. Escritor interno
-- ---------------------------------------------------------------------------

create or replace function public.auditoria_registrar(
  p_acao text,
  p_entidade text,
  p_entidade_id text default null,
  p_alvo_atendente_id bigint default null,
  p_alvo_user_id uuid default null,
  p_atendimento_id bigint default null,
  p_session_id text default null,
  p_dados jsonb default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_atendente_id bigint;
  v_nome text;
begin
  -- Resolve o ator diretamente (sem RLS) para funcionar em qualquer contexto.
  select p.atendente_id, p.nome into v_atendente_id, v_nome
  from public.profiles p
  where p.id = v_user_id;

  insert into public.auditoria_eventos (
    acao, entidade, entidade_id,
    ator_user_id, ator_atendente_id, ator_nome,
    alvo_atendente_id, alvo_user_id, atendimento_id, session_id, dados
  ) values (
    p_acao, p_entidade, p_entidade_id,
    v_user_id, v_atendente_id, coalesce(v_nome, 'sistema'),
    p_alvo_atendente_id, p_alvo_user_id, p_atendimento_id, p_session_id, p_dados
  );
end;
$$;

-- Só triggers/funções internas escrevem auditoria.
revoke execute on function public.auditoria_registrar(text, text, text, bigint, uuid, bigint, text, jsonb)
  from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 3. Bloqueio físico de alteração/remoção
-- ---------------------------------------------------------------------------
-- Defesa em profundidade: RLS já nega UPDATE/DELETE a `authenticated` (não há
-- policy), mas o trigger protege também contra service_role e contra um erro
-- futuro de policy — nem o n8n consegue apagar a trilha.

create or replace function public.auditoria_imutavel()
returns trigger
language plpgsql
as $$
begin
  raise exception 'A trilha de auditoria é append-only: % não é permitido', tg_op
    using errcode = '42501';
end;
$$;

drop trigger if exists auditoria_sem_update on public.auditoria_eventos;
create trigger auditoria_sem_update
  before update on public.auditoria_eventos
  for each row execute function public.auditoria_imutavel();

drop trigger if exists auditoria_sem_delete on public.auditoria_eventos;
create trigger auditoria_sem_delete
  before delete on public.auditoria_eventos
  for each row execute function public.auditoria_imutavel();

-- ---------------------------------------------------------------------------
-- 4. RLS
-- ---------------------------------------------------------------------------

alter table public.auditoria_eventos enable row level security;

-- Gestor lê tudo; atendente lê apenas os eventos em que ele é ator ou alvo.
drop policy if exists "auditoria leitura por escopo" on public.auditoria_eventos;
create policy "auditoria leitura por escopo" on public.auditoria_eventos
  for select
  to authenticated
  using (
    public.sou_gestor()
    or ator_user_id = (select auth.uid())
    or (
      alvo_atendente_id is not null
      and alvo_atendente_id = public.perfil_atendente_id()
    )
  );

-- Sem policy de INSERT/UPDATE/DELETE: o cliente não escreve nem apaga auditoria.

-- Privilégios explícitos: `authenticated` só lê. Escrever/alterar/apagar é
-- negado já no GRANT, além da ausência de policy e das triggers de imutabilidade.
grant select on public.auditoria_eventos to authenticated;
-- O projeto concede ALL por default privileges; o revoke abaixo é o que de fato
-- impede o cliente de forjar ou apagar um evento.
revoke insert, update, delete, truncate on public.auditoria_eventos from authenticated;
revoke all on public.auditoria_eventos from anon;

-- ---------------------------------------------------------------------------
-- 5. Triggers de auditoria em atendimentos
-- ---------------------------------------------------------------------------

create or replace function public.auditar_atendimento()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    perform public.auditoria_registrar(
      'atendimento.atribuido', 'atendimento', new.id::text,
      new.atendente_id, null, new.id, new.session_id,
      jsonb_build_object('departamento_id', new.departamento_id)
    );
    return new;
  end if;

  if new.atendente_id is distinct from old.atendente_id then
    perform public.auditoria_registrar(
      case when old.atendente_id is null then 'atendimento.atribuido'
           else 'atendimento.transferido' end,
      'atendimento', new.id::text,
      new.atendente_id, null, new.id, new.session_id,
      jsonb_build_object(
        'de_atendente_id', old.atendente_id,
        'para_atendente_id', new.atendente_id,
        'de_departamento_id', old.departamento_id,
        'para_departamento_id', new.departamento_id
      )
    );
  end if;

  if new.status is distinct from old.status and new.status = 'encerrado' then
    perform public.auditoria_registrar(
      'atendimento.encerrado', 'atendimento', new.id::text,
      new.atendente_id, null, new.id, new.session_id,
      jsonb_build_object('encerrado_em', new.encerrado_em)
    );
  end if;

  return new;
end;
$$;

drop trigger if exists auditar_atendimento_trg on public.atendimentos;
create trigger auditar_atendimento_trg
  after insert or update on public.atendimentos
  for each row execute function public.auditar_atendimento();

-- ---------------------------------------------------------------------------
-- 6. Triggers de auditoria em perfis (ações privilegiadas)
-- ---------------------------------------------------------------------------

create or replace function public.auditar_perfil()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    perform public.auditoria_registrar(
      'usuario.criado', 'perfil', new.id::text,
      new.atendente_id, new.id, null, null,
      jsonb_build_object('papel', new.papel, 'ativo', new.ativo)
    );
    return new;
  end if;

  if new.papel is distinct from old.papel then
    perform public.auditoria_registrar(
      'usuario.papel_alterado', 'perfil', new.id::text,
      new.atendente_id, new.id, null, null,
      jsonb_build_object('de', old.papel, 'para', new.papel)
    );
  end if;

  if new.ativo is distinct from old.ativo then
    perform public.auditoria_registrar(
      case when new.ativo then 'usuario.ativado' else 'usuario.desativado' end,
      'perfil', new.id::text,
      new.atendente_id, new.id, null, null, null
    );
  end if;

  if new.atendente_id is distinct from old.atendente_id then
    perform public.auditoria_registrar(
      'usuario.vinculo_alterado', 'perfil', new.id::text,
      new.atendente_id, new.id, null, null,
      jsonb_build_object('de_atendente_id', old.atendente_id, 'para_atendente_id', new.atendente_id)
    );
  end if;

  return new;
end;
$$;

drop trigger if exists auditar_perfil_trg on public.profiles;
create trigger auditar_perfil_trg
  after insert or update on public.profiles
  for each row execute function public.auditar_perfil();

