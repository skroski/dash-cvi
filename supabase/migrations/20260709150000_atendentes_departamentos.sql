select v.nome, v.cargo, d.id
from (
  values
    ('Veterinário(a) 1', 'Veterinário', 'Clínica'),
    ('Veterinário(a) 2', 'Veterinário', 'Clínica'),
    ('Veterinário(a) 3', 'Veterinário', 'Clínica'),
    ('Atendente Clínica 1', 'Atendente', 'Clínica'),
    ('Atendente Clínica 2', 'Atendente', 'Clínica')
) as v (nome, cargo, departamento)
join public.departamentos d on d.nome = v.departamento
on conflict (nome) do nothing;
