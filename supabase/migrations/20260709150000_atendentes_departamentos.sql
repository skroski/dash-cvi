-- Módulo de Atendentes e Departamentos + vínculo/transferência de atendimentos + notificações
-- Rodar no SQL Editor do Supabase (projeto napeofeenweerjhqucua) ou via `supabase db push`.

-- Departamentos (Clínica; editáveis no dashboard)
create table if not exists public.departamentos (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  cor text not null default '#0d9488',
  created_at timestamptz not null default now()
);

-- Atendentes / equipe (veterinários, atendentes)
create table if not exists public.atendentes (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  cargo text not null,
  departamento_id bigint references public.departamentos(id) on delete set null,
  ativo boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists atendentes_departamento_id_idx on public.atendentes (departamento_id);

-- Vínculo de um atendimento (conversa, identificada pelo session_id do chat)
-- com atendente/departamento. Apenas um atendimento aberto por conversa.
create table if not exists public.atendimentos (
  id bigint generated by default as identity primary key,
  session_id text not null,
  client_id bigint references public.dados_cliente(id) on delete set null,
  atendente_id bigint references public.atendentes(id) on delete set null,
  departamento_id bigint references public.departamentos(id) on delete set null,
  status text not null default 'aberto' check (status in ('aberto', 'encerrado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  encerrado_em timestamptz
);

create unique index if not exists atendimentos_session_aberto_uidx
  on public.atendimentos (session_id)
  where status = 'aberto';
create index if not exists atendimentos_atendente_id_idx on public.atendimentos (atendente_id);
create index if not exists atendimentos_departamento_id_idx on public.atendimentos (departamento_id);

-- Histórico de transferências entre atendentes/departamentos
create table if not exists public.atendimento_transferencias (
  id bigint generated by default as identity primary key,
  atendimento_id bigint not null references public.atendimentos(id) on delete cascade,
  de_atendente_id bigint references public.atendentes(id) on delete set null,
  para_atendente_id bigint references public.atendentes(id) on delete set null,
  de_departamento_id bigint references public.departamentos(id) on delete set null,
  para_departamento_id bigint references public.departamentos(id) on delete set null,
  motivo text,
  created_at timestamptz not null default now()
);

create index if not exists atendimento_transferencias_atendimento_id_idx
  on public.atendimento_transferencias (atendimento_id);

-- Notificações do sistema (atribuições, transferências, encerramentos)
create table if not exists public.notificacoes (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('atribuicao', 'transferencia', 'encerramento')),
  titulo text not null,
  descricao text,
  session_id text,
  atendimento_id bigint references public.atendimentos(id) on delete cascade,
  atendente_id bigint references public.atendentes(id) on delete cascade,
  departamento_id bigint references public.departamentos(id) on delete cascade,
  lida boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists notificacoes_lida_idx on public.notificacoes (lida);
create index if not exists notificacoes_created_at_idx on public.notificacoes (created_at desc);

-- O dashboard acessa o banco com a anon key (mesmo modelo das tabelas existentes),
-- então as policies liberam acesso total.
alter table public.departamentos enable row level security;
alter table public.atendentes enable row level security;
alter table public.atendimentos enable row level security;
alter table public.atendimento_transferencias enable row level security;
alter table public.notificacoes enable row level security;

drop policy if exists "acesso total departamentos" on public.departamentos;
create policy "acesso total departamentos" on public.departamentos
  for all using (true) with check (true);

drop policy if exists "acesso total atendentes" on public.atendentes;
create policy "acesso total atendentes" on public.atendentes
  for all using (true) with check (true);

drop policy if exists "acesso total atendimentos" on public.atendimentos;
create policy "acesso total atendimentos" on public.atendimentos
  for all using (true) with check (true);

drop policy if exists "acesso total atendimento_transferencias" on public.atendimento_transferencias;
create policy "acesso total atendimento_transferencias" on public.atendimento_transferencias
  for all using (true) with check (true);

drop policy if exists "acesso total notificacoes" on public.notificacoes;
create policy "acesso total notificacoes" on public.notificacoes
  for all using (true) with check (true);

-- Realtime: notificações chegam ao vivo em todos os dashboards abertos
do $$
begin
  alter publication supabase_realtime add table public.notificacoes;
exception
  when duplicate_object then null;
end $$;

do $$
begin
  alter publication supabase_realtime add table public.atendimentos;
exception
  when duplicate_object then null;
end $$;

