-- 7. Sincronização mensagem -> agenda e linha do tempo
-- ---------------------------------------------------------------------------

create or replace function public.lembrete_mensagens_sincronizar()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_quando text;
begin
  if tg_op = 'INSERT' then
    v_quando := to_char(new.programado_para at time zone 'America/Sao_Paulo', 'DD/MM "às" HH24:MI:SS');
    insert into public.lembrete_eventos (mensagem_id, tipo, descricao)
    values (
      new.id,
      'planejado',
      case new.disparo
        when 'teste' then 'Mensagem de teste programada para ' || v_quando || '.'
        when 'manual' then 'Envio manual programado para ' || v_quando || '.'
        else 'Lembrete programado para ' || v_quando || '.'
      end
    );
    return null;
  end if;

  if new.status is not distinct from old.status then
    return null;
  end if;

  if new.status = 'pendente' then
    insert into public.lembrete_eventos (mensagem_id, tipo, descricao)
    values (
      new.id,
      'reagendado',
      'Reenvio programado para '
        || to_char(new.programado_para at time zone 'America/Sao_Paulo', 'DD/MM "às" HH24:MI:SS') || '.'
    );
  elsif new.status in ('enviado', 'falha', 'ignorado', 'cancelado') then
    insert into public.lembrete_eventos (mensagem_id, tipo, descricao, dados)
    values (
      new.id,
      new.status,
      case new.status
        when 'enviado' then 'Mensagem entregue ao WhatsApp'
          || case new.origem_texto
               when 'ia' then ' (texto escrito pela IA).'
               when 'manual' then ' (texto revisado no painel).'
               else ' (frase de exemplo).'
             end
        when 'falha' then coalesce(new.erro, 'Falha no envio.')
        when 'ignorado' then coalesce(new.erro, 'Mensagem não enviada.')
        else coalesce(new.erro, 'Lembrete cancelado no painel.')
      end,
      jsonb_strip_nulls(jsonb_build_object(
        'tentativas', new.tentativas,
        'provider_message_id', new.provider_message_id
      ))
    );
  end if;

  if new.disparo = 'teste' then
    return null;
  end if;

  update public.lembrete_envios e
  set
    status = case new.status
      when 'cancelado' then 'ignorado'
      else new.status
    end,
    erro = case
      when new.status = 'cancelado' then 'Lembrete cancelado no painel.'
      when new.status in ('falha', 'ignorado') then new.erro
      else null
    end,
    tentativas = greatest(e.tentativas, new.tentativas),
    provider_message_id = coalesce(new.provider_message_id, e.provider_message_id),
    enviado_em = case when new.status = 'enviado' then new.enviado_em else e.enviado_em end
  where e.mensagem_id = new.id
    and e.status <> 'cancelado';

  return null;
end;
$$;

drop trigger if exists lembrete_mensagens_sincronizar on public.lembrete_mensagens;
create trigger lembrete_mensagens_sincronizar
after insert or update of status on public.lembrete_mensagens
for each row execute function public.lembrete_mensagens_sincronizar();

-- Recalcula pets, serviços e horário da mensagem a partir da agenda vinculada.
create or replace function public.lembrete_recalcular_mensagem(p_mensagem_id bigint)
returns void
language sql
security definer
set search_path = ''
as $$
  update public.lembrete_mensagens m
  set
    nomes_pets = coalesce(x.pets, '{}'),
    servicos = coalesce(x.servicos, '{}'),
    servicos_texto = coalesce(x.servicos_texto, '{}'),
    horario_agendado = x.horario,
    data_agendada = coalesce(x.data_agendada, m.data_agendada),
    telefone = coalesce(x.telefone, m.telefone),
    nome_tutor = coalesce(x.nome_tutor, m.nome_tutor),
    -- Conteúdo mudou: o texto (se já escrito) é refeito no envio.
    texto = case
      when m.nomes_pets is distinct from coalesce(x.pets, '{}')
        or m.servicos is distinct from coalesce(x.servicos, '{}')
        or m.servicos_texto is distinct from coalesce(x.servicos_texto, '{}')
        or m.horario_agendado is distinct from x.horario
      then null
      else m.texto
    end
  from (
    select
      array_agg(distinct btrim(e.nome_pet))
        filter (where nullif(btrim(e.nome_pet), '') is not null) as pets,
      array_agg(distinct coalesce(s.nome, btrim(e.servico)))
        filter (where coalesce(s.nome, nullif(btrim(e.servico), '')) is not null) as servicos,
      -- O que aparece no texto: texto do agendamento, depois o da categoria,
      -- depois o nome da categoria, depois o texto importado.
      array_agg(distinct coalesce(
          nullif(btrim(e.servico_texto), ''), nullif(btrim(s.texto_mensagem), ''), s.nome, btrim(e.servico)
        ))
        filter (where coalesce(
          nullif(btrim(e.servico_texto), ''), nullif(btrim(s.texto_mensagem), ''), s.nome, nullif(btrim(e.servico), '')
        ) is not null) as servicos_texto,
      min(e.horario_agendado) as horario,
      min(e.data_agendada) as data_agendada,
      (array_agg(e.telefone order by e.horario_agendado nulls last, e.id))[1] as telefone,
      (array_agg(btrim(e.nome_tutor) order by e.horario_agendado nulls last, e.id))[1] as nome_tutor
    from public.lembrete_envios e
    left join public.lembrete_servicos s on s.id = e.servico_id
    where e.mensagem_id = p_mensagem_id
      and e.status <> 'cancelado'
  ) x
  where m.id = p_mensagem_id;
$$;

-- Mudou o texto (ou o nome) de um serviço: as mensagens ainda na fila que o
-- usam passam a ter o texto novo (e são reescritas no envio).
create or replace function public.lembrete_servicos_atualizar_mensagens()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
begin
  for v_id in
    select distinct m.id
    from public.lembrete_mensagens m
    join public.lembrete_envios e on e.mensagem_id = m.id
    where e.servico_id = new.id
      and m.status = 'pendente'
      and m.disparo <> 'teste'
