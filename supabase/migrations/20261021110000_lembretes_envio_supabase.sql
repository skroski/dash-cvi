-- Lembretes 100% no Supabase (substitui o fluxo n8n "LembretesVacinas").
--
-- O dashboard gerencia agenda, serviços, regras e frases de exemplo. O pg_cron
-- chama public.lembretes_tick() a cada minuto: ele planeja a fila do dia
-- (1 mensagem por tutor por dia) e aciona a edge function `lembretes`, que
-- escreve o texto com a OpenAI e envia pela uazapi com intervalo aleatório.
--
-- Mapeamento completo do fluxo antigo: docs/lembretes-migracao-n8n.md
-- Passo a passo de implantação:      docs/lembretes-implantacao.md

