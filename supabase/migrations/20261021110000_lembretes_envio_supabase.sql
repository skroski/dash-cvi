-- "Enviar lembrete agora" de um agendamento: junta os outros agendamentos do
-- mesmo tutor na mesma data e respeita o limite de 1 por dia.
create or replace function public.lembretes_enviar_agendamento(p_envio_id bigint)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_envio public.lembrete_envios%rowtype;
  v_hoje date;
  v_mensagem_id bigint;
begin
  perform public.lembretes_exigir_login();

  select * into v_envio
  from public.lembrete_envios e
  where e.id = p_envio_id;
  if not found then
    raise exception 'Agendamento não encontrado.' using errcode = 'P0002';
  end if;
  if v_envio.configuracao_id is null then
    raise exception 'Escolha uma regra para este agendamento antes de enviar.' using errcode = 'P0001';
  end if;
  if v_envio.status not in ('pendente', 'falha', 'ignorado') then
    raise exception 'Este agendamento não está aguardando lembrete.' using errcode = 'P0001';
  end if;

  v_hoje := (now() at time zone 'America/Sao_Paulo')::date;
  if v_envio.data_agendada < v_hoje then
    raise exception 'A data deste agendamento já passou.' using errcode = 'P0001';
  end if;

  if exists (
    select 1 from public.lembrete_mensagens m
    where m.telefone_chave = v_envio.telefone_chave
      and m.dia_envio = v_hoje
      and m.disparo <> 'teste'
      and m.status in ('enviado', 'processando')
  ) then
    raise exception 'Este tutor já recebeu um lembrete hoje (limite de 1 por dia).' using errcode = 'P0001';
  end if;

  -- Já está na fila: mantém o horário e passa a valer como envio manual
  -- (sai mesmo com o envio automático desligado).
  if v_envio.status = 'pendente' and v_envio.mensagem_id is not null then
    update public.lembrete_mensagens m
    set disparo = 'manual'
    where m.id = v_envio.mensagem_id
      and m.status = 'pendente';
    if found then
      return v_envio.mensagem_id;
    end if;
  end if;

  update public.lembrete_envios e
  set status = 'pendente', erro = null, mensagem_id = null
  where e.id = v_envio.id;

  perform public.lembrete_enfileirar(
    v_envio.configuracao_id,
    v_envio.data_agendada,
    now(),
    'manual',
    v_envio.telefone_chave
  );

  select e.mensagem_id into v_mensagem_id
  from public.lembrete_envios e
  where e.id = v_envio.id;
  return v_mensagem_id;
end;
$$;

create or replace function public.lembretes_reenviar_mensagem(p_mensagem_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_msg public.lembrete_mensagens%rowtype;
  v_hoje date := (now() at time zone 'America/Sao_Paulo')::date;
begin
  perform public.lembretes_exigir_login();

  select * into v_msg
  from public.lembrete_mensagens m
  where m.id = p_mensagem_id
  for update;
  if not found then
    raise exception 'Mensagem não encontrada.' using errcode = 'P0002';
  end if;
  if v_msg.status not in ('falha', 'ignorado', 'cancelado') then
    raise exception 'Só é possível reenviar mensagens com falha, ignoradas ou canceladas.' using errcode = 'P0001';
  end if;

  if v_msg.disparo <> 'teste' then
    if v_msg.data_agendada < v_hoje then
      raise exception 'A data do agendamento já passou.' using errcode = 'P0001';
    end if;
    -- Mensagem de outro dia passa a contar como o lembrete de hoje.
    if v_msg.dia_envio < v_hoje and exists (
      select 1 from public.lembrete_mensagens m
      where m.telefone_chave = v_msg.telefone_chave
        and m.dia_envio = v_hoje
        and m.disparo <> 'teste'
    ) then
      raise exception 'Este tutor já tem um lembrete hoje (limite de 1 por dia).' using errcode = 'P0001';
    end if;

    update public.lembrete_envios e
    set status = 'pendente', erro = null
    where e.mensagem_id = v_msg.id
      and e.status <> 'cancelado';
    perform public.lembrete_recalcular_mensagem(v_msg.id);
  end if;

  update public.lembrete_mensagens m
  set
    status = 'pendente',
    disparo = case when m.disparo = 'teste' then 'teste' else 'manual' end,
    dia_envio = case when m.disparo = 'teste' then m.dia_envio else greatest(m.dia_envio, v_hoje) end,
    texto = null,
    origem_texto = null,
    exemplo_indice = null,
    erro = null,
    programado_para = case
      when m.disparo = 'teste' then now()
      else public.lembrete_proximo_horario(m.configuracao_id, now())
    end
  where m.id = v_msg.id;
end;
$$;

