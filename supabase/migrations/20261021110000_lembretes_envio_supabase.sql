-- Realtime para o painel acompanhar a fila ao vivo.
do $$
declare
  v_tabela text;
begin
  foreach v_tabela in array array[
    'lembrete_servicos', 'lembrete_ajustes', 'lembrete_mensagens', 'lembrete_eventos'
  ]
  loop
    begin
      execute format('alter publication supabase_realtime add table public.%I', v_tabela);
    exception
      when duplicate_object then null;
      when undefined_object then null;
    end;
  end loop;
end $$;
