-- Serviço removido sai também da lista de serviços das regras.
create or replace function public.lembrete_servicos_remover_das_regras()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.lembrete_configuracoes c
  set servico_ids = array_remove(c.servico_ids, old.id)
  where old.id = any (c.servico_ids);
  return null;
end;
$$;

