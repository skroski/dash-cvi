-- Envio direto pelo painel ("Enviar agora" com o texto revisado). O navegador
-- chama o WhatsApp, então o banco precisa saber ANTES, para o cron não mandar
-- a mesma mensagem de novo:
--   1. lembretes_reservar_envio_manual: grava o texto e põe a mensagem em
--      "processando" (o cron só pega "pendente");
--   2. o navegador envia pela uazapi;
--   3. lembretes_concluir_envio_manual: marca "enviado" ou "falha".
-- Se o navegador fechar no meio, a rotina de recuperação marca a mensagem como
-- falha depois de 10 minutos, pedindo para conferir o WhatsApp antes de reenviar.
create or replace function public.lembretes_reservar_envio_manual(
  p_mensagem_id bigint,
  p_texto text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_msg public.lembrete_mensagens%rowtype;
  v_hoje date := (now() at time zone 'America/Sao_Paulo')::date;
  v_texto text := btrim(coalesce(p_texto, ''));
begin
  perform public.lembretes_exigir_login();

  if length(v_texto) < 5 or length(v_texto) > 1200 then
    raise exception 'O texto precisa ter entre 5 e 1200 caracteres.' using errcode = 'P0001';
  end if;

  select * into v_msg
  from public.lembrete_mensagens m
  where m.id = p_mensagem_id
  for update;
  if not found then
    raise exception 'Mensagem não encontrada.' using errcode = 'P0002';
  end if;
  if v_msg.status not in ('pendente', 'falha', 'ignorado', 'cancelado') then
    raise exception 'Esta mensagem já foi enviada ou está sendo enviada.' using errcode = 'P0001';
  end if;

  if v_msg.disparo <> 'teste' then
    if v_msg.data_agendada < v_hoje then
      raise exception 'A data do agendamento já passou.' using errcode = 'P0001';
    end if;
    if exists (
      select 1 from public.lembrete_mensagens m
      where m.telefone_chave = v_msg.telefone_chave
        and m.dia_envio = v_hoje
        and m.disparo <> 'teste'
        and m.id <> v_msg.id
        and m.status in ('enviado', 'processando')
    ) then
      raise exception 'Este tutor já recebeu (ou está recebendo) um lembrete hoje (limite de 1 por dia).'
        using errcode = 'P0001';
    end if;
  end if;

  update public.lembrete_mensagens m
  set
    status = 'processando',
    disparo = case when m.disparo = 'teste' then 'teste' else 'manual' end,
    dia_envio = case when m.disparo = 'teste' then m.dia_envio else greatest(m.dia_envio, v_hoje) end,
    texto = v_texto,
    origem_texto = 'manual',
    exemplo_indice = null,
    modelo_ia = null,
    erro = null,
    tentativas = m.tentativas + 1,
    processando_desde = now()
  where m.id = v_msg.id;
end;
$$;

create or replace function public.lembretes_concluir_envio_manual(
  p_mensagem_id bigint,
  p_enviado boolean,
  p_provider_message_id text default null,
  p_erro text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_status text;
  v_origem text;
begin
  perform public.lembretes_exigir_login();

  select m.status, m.origem_texto into v_status, v_origem
  from public.lembrete_mensagens m
  where m.id = p_mensagem_id
  for update;
  if not found then
    raise exception 'Mensagem não encontrada.' using errcode = 'P0002';
  end if;
  if v_status <> 'processando' or v_origem is distinct from 'manual' then
    raise exception 'Esta mensagem não está em envio manual.' using errcode = 'P0001';
  end if;

  if p_enviado then
    update public.lembrete_mensagens m
    set
      status = 'enviado',
      enviado_em = now(),
      provider_message_id = nullif(btrim(coalesce(p_provider_message_id, '')), ''),
      erro = null,
      processando_desde = null
    where m.id = p_mensagem_id;
  else
    update public.lembrete_mensagens m
    set
      status = 'falha',
      erro = coalesce(nullif(btrim(coalesce(p_erro, '')), ''), 'Falha no envio pelo painel.'),
      processando_desde = null
    where m.id = p_mensagem_id;
  end if;
end;
$$;

-- Mensagem de teste para o número informado (ou o telefone de teste dos
-- ajustes), com dados fictícios. Não conta no limite de 1 por dia.
create or replace function public.lembretes_enviar_teste(
  p_configuracao_id bigint,
  p_telefone text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cfg public.lembrete_configuracoes%rowtype;
  v_telefone text;
  v_servico text;
  v_id bigint;
  v_hoje date;
begin
  perform public.lembretes_exigir_login();

  select * into v_cfg
