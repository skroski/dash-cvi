-- Mantém uma mensagem ainda na fila coerente com a agenda: tira atendimentos
-- remarcados, recalcula pets e serviços e cancela a mensagem se não sobrou
-- nenhum atendimento ativo (cancelado ou excluído depois do planejamento).
create or replace function public.lembrete_revisar_mensagem(p_mensagem_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_msg public.lembrete_mensagens%rowtype;
begin
  select * into v_msg
  from public.lembrete_mensagens m
  where m.id = p_mensagem_id;
  if not found or v_msg.disparo = 'teste' or v_msg.status <> 'pendente' then
    return;
  end if;

  update public.lembrete_envios e
  set mensagem_id = null, status = 'pendente', erro = null
  where e.mensagem_id = v_msg.id
    and e.data_agendada <> v_msg.data_agendada
    and e.status <> 'cancelado';

  if not exists (
    select 1 from public.lembrete_envios e
    where e.mensagem_id = v_msg.id
      and e.status <> 'cancelado'
  ) then
    update public.lembrete_mensagens m
    set status = 'cancelado',
        erro = 'Atendimento cancelado ou removido da agenda antes do envio.'
    where m.id = v_msg.id;
    return;
  end if;

  perform public.lembrete_recalcular_mensagem(v_msg.id);
end;
$$;

-- Edição, cancelamento ou exclusão na agenda revisam na hora a mensagem que
-- ainda está na fila. Não roda dentro de outros gatilhos (evita recursão com
-- a sincronização mensagem -> agenda).
create or replace function public.lembrete_envios_revisar_fila()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if pg_catalog.pg_trigger_depth() > 1 then
    return null;
  end if;
  if tg_op = 'DELETE' then
    if old.mensagem_id is not null then
      perform public.lembrete_revisar_mensagem(old.mensagem_id);
    end if;
    return null;
  end if;
  if old.mensagem_id is not null then
    perform public.lembrete_revisar_mensagem(old.mensagem_id);
  end if;
  if new.mensagem_id is not null and new.mensagem_id is distinct from old.mensagem_id then
    perform public.lembrete_revisar_mensagem(new.mensagem_id);
  end if;
  return null;
end;
$$;

drop trigger if exists lembrete_envios_revisar_fila on public.lembrete_envios;
create trigger lembrete_envios_revisar_fila
after update of status, nome_pet, nome_tutor, telefone, servico, servico_id, servico_texto, data_agendada, horario_agendado
  or delete
on public.lembrete_envios
for each row execute function public.lembrete_envios_revisar_fila();

-- Próximo horário livre na fila de envio: depois da última mensagem
-- programada, em envio ou enviada nos últimos minutos, com o intervalo
-- aleatório da regra. Vale para lotes, reenvios e "enviar agora", para o
-- WhatsApp nunca receber disparos colados.
create or replace function public.lembrete_proximo_horario(
  p_configuracao_id bigint,
  p_agora timestamptz,
  p_ultimo timestamptz default null
)
returns timestamptz
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_min smallint := 20;
  v_max smallint := 50;
  v_ultimo timestamptz := p_ultimo;
begin
  select c.intervalo_min_segundos, c.intervalo_max_segundos into v_min, v_max
  from public.lembrete_configuracoes c
  where c.id = p_configuracao_id;
  v_min := coalesce(v_min, 20);
  v_max := coalesce(v_max, 50);

  if v_ultimo is null then
    select max(x.momento) into v_ultimo
    from (
      select m.programado_para as momento
      from public.lembrete_mensagens m
      where m.status in ('pendente', 'processando')
        and m.disparo <> 'teste'
      union all
      select m.enviado_em
      from public.lembrete_mensagens m
      where m.status = 'enviado'
        and m.disparo <> 'teste'
        and m.enviado_em > p_agora - interval '10 minutes'
    ) x;
  end if;

  if v_ultimo is null then
    return p_agora;
  end if;
  return greatest(
    p_agora,
    v_ultimo + make_interval(secs => v_min + floor(random() * (v_max - v_min + 1)))
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- 8. Planejamento da fila
-- ---------------------------------------------------------------------------

-- Agrupa os agendamentos pendentes de uma regra e data por tutor e garante uma
-- única mensagem por tutor no dia. Mensagens novas recebem horários com
-- intervalo aleatório acumulado (o "debounce" que no n8n era o node Wait).
create or replace function public.lembrete_enfileirar(
  p_configuracao_id bigint,
  p_data_agendada date,
  p_agora timestamptz,
  p_disparo text,
  p_telefone_chave text default null
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cfg public.lembrete_configuracoes%rowtype;
  v_dia date;
  v_slot timestamptz;
  v_grupo record;
  v_msg public.lembrete_mensagens%rowtype;
  v_novas integer := 0;
begin
  -- Cron e botões do painel podem planejar ao mesmo tempo: serializa.
  perform pg_advisory_xact_lock(hashtext('lembrete_enfileirar'));

  select * into v_cfg
  from public.lembrete_configuracoes c
  where c.id = p_configuracao_id;
  if not found then
    return 0;
  end if;

  v_dia := (p_agora at time zone v_cfg.timezone)::date;

  -- Cada mensagem nova pega o próximo horário livre: a primeira depois da
  -- fila atual, as seguintes com o intervalo aleatório entre elas.

  for v_grupo in
    select
      e.telefone_chave,
      array_agg(e.id order by e.horario_agendado nulls last, e.id) as envio_ids,
      (array_agg(e.telefone order by e.horario_agendado nulls last, e.id))[1] as telefone,
      (array_agg(btrim(e.nome_tutor) order by e.horario_agendado nulls last, e.id))[1] as nome_tutor,
      min(e.horario_agendado) as primeiro_horario
    from public.lembrete_envios e
    where e.configuracao_id = v_cfg.id
      and e.status = 'pendente'
      and e.mensagem_id is null
      and e.data_agendada = p_data_agendada
      and e.data_agendada >= v_dia
      and length(e.telefone_chave) >= 10
      and public.lembrete_normalizar(e.status_agendamento) not in (
        'cancelado', 'cancelada', 'desmarcado', 'desmarcada',
        'faltou', 'remarcado', 'remarcada'
      )
      and (
        not v_cfg.somente_confirmados
        or public.lembrete_normalizar(e.status_agendamento) = 'confirmado'
      )
      and (p_telefone_chave is null or e.telefone_chave = p_telefone_chave)
    group by e.telefone_chave
    order by min(e.horario_agendado) nulls last, (array_agg(btrim(e.nome_tutor)))[1]
  loop
    select * into v_msg
    from public.lembrete_mensagens m
    where m.telefone_chave = v_grupo.telefone_chave
      and m.dia_envio = v_dia
      and m.disparo <> 'teste'
    for update;

    if not found then
      v_slot := public.lembrete_proximo_horario(v_cfg.id, p_agora, v_slot);

      insert into public.lembrete_mensagens (
        configuracao_id, configuracao_nome, disparo, dia_envio,
        telefone, telefone_chave, nome_tutor, data_agendada,
        horario_agendado, programado_para,
        categoria, botoes_confirmacao, pausa_ia_minutos
      )
      values (
        v_cfg.id, v_cfg.nome, p_disparo, v_dia,
        v_grupo.telefone, v_grupo.telefone_chave, v_grupo.nome_tutor, p_data_agendada,
        v_grupo.primeiro_horario, v_slot,
        coalesce(v_cfg.categoria, 'consulta'), coalesce(v_cfg.botoes_confirmacao, false),
        coalesce(v_cfg.pausa_ia_minutos, 1.5)
      )
      returning * into v_msg;

      update public.lembrete_envios e
      set mensagem_id = v_msg.id
      where e.id = any (v_grupo.envio_ids);

      perform public.lembrete_recalcular_mensagem(v_msg.id);
      v_novas := v_novas + 1;

    elsif v_msg.status = 'pendente' then
      -- Ainda não saiu: o agendamento novo entra na mesma mensagem.
      update public.lembrete_envios e
      set mensagem_id = v_msg.id
      where e.id = any (v_grupo.envio_ids);

      update public.lembrete_mensagens m
      set
        texto = null,
        origem_texto = null,
        exemplo_indice = null,
        disparo = case when p_disparo = 'manual' then 'manual' else m.disparo end
      where m.id = v_msg.id;

      perform public.lembrete_recalcular_mensagem(v_msg.id);

    elsif p_disparo = 'manual' and v_msg.status in ('falha', 'ignorado', 'cancelado') then
      -- Pedido explícito no painel: reaproveita a mensagem do dia.
      update public.lembrete_envios e
      set mensagem_id = v_msg.id
      where e.id = any (v_grupo.envio_ids);

      perform public.lembrete_recalcular_mensagem(v_msg.id);

      v_slot := public.lembrete_proximo_horario(v_cfg.id, p_agora, v_slot);

      update public.lembrete_mensagens m
      set
        status = 'pendente',
        disparo = 'manual',
        texto = null,
        origem_texto = null,
        exemplo_indice = null,
        erro = null,
        programado_para = v_slot
      where m.id = v_msg.id;

    else
      -- Tutor já recebeu (ou está recebendo) o lembrete de hoje.
      update public.lembrete_envios e
      set
        mensagem_id = v_msg.id,
        status = 'ignorado',
        erro = 'Tutor já recebeu um lembrete hoje (limite de 1 por dia).'
      where e.id = any (v_grupo.envio_ids);
    end if;
  end loop;

  return v_novas;
end;
$$;

-- Planejamento chamado pelo cron. Para cada regra ativa cujo horário já
-- chegou (e cuja janela ainda não passou), enfileira os agendamentos da data
-- alvo (hoje + antecedência). É idempotente: rodar de novo só pega
-- agendamentos que entraram depois.
create or replace function public.lembretes_planejar(
  p_agora timestamptz default now(),
  p_configuracao_id bigint default null,
  p_forcar boolean default false
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cfg public.lembrete_configuracoes%rowtype;
  v_hoje date;
  v_inicio timestamptz;
  v_total integer := 0;
begin
  if not p_forcar and not coalesce(
    (select a.envio_automatico from public.lembrete_ajustes a where a.id = 1),
    false
  ) then
    return 0;
  end if;

  for v_cfg in
    select *
    from public.lembrete_configuracoes c
    where c.ativo
      and (p_configuracao_id is null or c.id = p_configuracao_id)
    order by c.horario_envio, c.id
  loop
    v_hoje := (p_agora at time zone v_cfg.timezone)::date;
    v_inicio := (v_hoje + v_cfg.horario_envio) at time zone v_cfg.timezone;

    if not p_forcar and (
      p_agora < v_inicio
      or p_agora >= v_inicio + make_interval(hours => v_cfg.janela_envio_horas)
    ) then
      continue;
    end if;

    v_total := v_total + public.lembrete_enfileirar(
      v_cfg.id,
      v_hoje + v_cfg.dias_antecedencia,
      p_agora,
      case when p_forcar then 'manual' else 'automatico' end
    );
  end loop;

  return v_total;
end;
$$;

-- Reivindica as mensagens que vencem nos próximos segundos para a edge
-- function. Antes, aplica as travas de segurança:
--   * mensagem que passou da janela da regra vira "ignorado" (nunca dispara
--     lembrete atrasado em massa);
--   * mensagem presa em "processando" vira "falha" (pode ter saído ou não; o
--     reenvio é decisão humana no painel).
create or replace function public.lembretes_reivindicar(
  p_limite integer default 10,
  p_horizonte_segundos integer default 55
)
returns setof public.lembrete_mensagens
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_automatico boolean;
  v_id bigint;
begin
  update public.lembrete_mensagens m
  set
    status = 'ignorado',
    erro = 'Fora da janela de envio: não foi enviado para evitar um lembrete atrasado.'
  where m.status = 'pendente'
    and m.programado_para < now() - make_interval(hours => coalesce(
      (select c.janela_envio_horas from public.lembrete_configuracoes c where c.id = m.configuracao_id),
      3
    ));

  update public.lembrete_mensagens m
  set
    status = 'falha',
    erro = 'Envio interrompido antes da confirmação. Confira no WhatsApp se a mensagem chegou antes de reenviar.'
  where m.status = 'processando'
    and m.processando_desde < now() - interval '10 minutes';

  select coalesce(a.envio_automatico, false) into v_automatico
  from public.lembrete_ajustes a
  where a.id = 1;

  -- Última conferência com a agenda antes de entregar para envio.
  for v_id in
    select m.id
    from public.lembrete_mensagens m
    where m.status = 'pendente'
      and m.disparo <> 'teste'
      and m.programado_para <= now()
        + make_interval(secs => greatest(0, least(coalesce(p_horizonte_segundos, 55), 110)))
  loop
    perform public.lembrete_revisar_mensagem(v_id);
  end loop;

  return query
  with vencidas as (
    select m.id
    from public.lembrete_mensagens m
    where m.status = 'pendente'
      and m.programado_para <= now()
        + make_interval(secs => greatest(0, least(coalesce(p_horizonte_segundos, 55), 110)))
      and (coalesce(v_automatico, false) or m.disparo in ('manual', 'teste'))
    order by m.programado_para
    for update skip locked
    limit greatest(1, least(coalesce(p_limite, 10), 50))
  )
  update public.lembrete_mensagens m
  set
    status = 'processando',
    tentativas = m.tentativas + 1,
    processando_desde = now()
  from vencidas
  where m.id = vencidas.id
  returning m.*;
end;
$$;

-- Executado pelo pg_cron a cada minuto. Planeja e, se houver mensagem para os
-- próximos 60 segundos, chama a edge function. URL e segredo vêm do Vault.
create or replace function public.lembretes_tick()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_url text;
  v_segredo text;
  v_automatico boolean;
begin
  perform public.lembretes_planejar(now());

  select coalesce(a.envio_automatico, false) into v_automatico
  from public.lembrete_ajustes a
  where a.id = 1;

  if not exists (
    select 1
    from public.lembrete_mensagens m
    where m.status = 'pendente'
      and m.programado_para <= now() + interval '60 seconds'
      and (v_automatico or m.disparo in ('manual', 'teste'))
  ) then
    return;
  end if;

  select s.decrypted_secret into v_url
  from vault.decrypted_secrets s
  where s.name = 'lembretes_function_url';
  select s.decrypted_secret into v_segredo
  from vault.decrypted_secrets s
  where s.name = 'lembretes_cron_secret';

  if v_url is null or v_segredo is null then
    if not exists (
      select 1 from public.lembrete_eventos ev
      where ev.tipo = 'erro_sistema'
        and ev.dados ->> 'codigo' = 'vault_ausente'
        and ev.created_at > now() - interval '1 hour'
    ) then
      insert into public.lembrete_eventos (tipo, descricao, dados)
      values (
        'erro_sistema',
        'Segredos do Vault ausentes (lembretes_function_url / lembretes_cron_secret). A fila não está sendo enviada.',
        jsonb_build_object('codigo', 'vault_ausente')
      );
    end if;
    return;
  end if;

  perform net.http_post(
    url := v_url,
    body := jsonb_build_object('acao', 'processar'),
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'X-Cron-Secret', v_segredo
    ),
    timeout_milliseconds := 10000
  );
end;
$$;

