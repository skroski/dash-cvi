    raise exception 'Informe um WhatsApp de teste com DDD.' using errcode = 'P0001';
  end if;
  if length(v_telefone) in (10, 11) then
    v_telefone := '55' || v_telefone;
  end if;

  select coalesce(nullif(btrim(s.texto_mensagem), ''), s.nome) into v_servico
  from public.lembrete_servicos s
  where s.ativo
    and (cardinality(v_cfg.servico_ids) = 0 or s.id = any (v_cfg.servico_ids))
  order by s.ordem, s.nome
  limit 1;

  v_hoje := (now() at time zone v_cfg.timezone)::date;

  insert into public.lembrete_mensagens (
    configuracao_id, configuracao_nome, disparo, dia_envio, telefone,
    telefone_chave, nome_tutor, nomes_pets, servicos, servicos_texto, data_agendada,
    horario_agendado, programado_para,
    categoria, botoes_confirmacao, pausa_ia_minutos
  )
  values (
    v_cfg.id, v_cfg.nome, 'teste', v_hoje, v_telefone,
    public.lembrete_telefone_chave(v_telefone), 'Mariana', array['Toby'],
    array[coalesce(v_servico, 'Consulta Veterinária')],
    array[coalesce(v_servico, 'consulta veterinária')],
    v_hoje + v_cfg.dias_antecedencia, time '10:30', now(),
    coalesce(v_cfg.categoria, 'consulta'), coalesce(v_cfg.botoes_confirmacao, false),
    coalesce(v_cfg.pausa_ia_minutos, 1.5)
  )
  returning id into v_id;

  return v_id;
end;
$$;

-- Diagnóstico para a tela de ajustes: cron ligado, segredos do Vault, fila.
create or replace function public.lembretes_diagnostico()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cron boolean := false;
  v_ultima timestamptz;
  v_vault boolean := false;
begin
  perform public.lembretes_exigir_login();

  begin
    execute $q$select exists (select 1 from cron.job where jobname = 'lembretes-worker' and active)$q$
      into v_cron;
    execute $q$
      select max(d.start_time)
      from cron.job_run_details d
      join cron.job j on j.jobid = d.jobid
      where j.jobname = 'lembretes-worker'
    $q$ into v_ultima;
  exception when others then
    v_cron := false;
  end;

  begin
    execute $q$
      select count(*) = 2 from vault.decrypted_secrets
      where name in ('lembretes_function_url', 'lembretes_cron_secret')
    $q$ into v_vault;
  exception when others then
    v_vault := false;
  end;

  return jsonb_build_object(
    'cron_ativo', v_cron,
    'cron_ultima_execucao', v_ultima,
    'vault_configurado', v_vault,
    'fila_pendente', (select count(*) from public.lembrete_mensagens m where m.status = 'pendente'),
    'fila_processando', (select count(*) from public.lembrete_mensagens m where m.status = 'processando')
  );
end;
$$;

