-- Completa categoria, regra e horário previsto de qualquer agendamento, venha
-- ele do painel, da importação ou de uma integração externa.
create or replace function public.lembrete_envios_preparar()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_cfg public.lembrete_configuracoes%rowtype;
  v_servico public.lembrete_servicos%rowtype;
begin
  new.servico_texto := nullif(btrim(new.servico_texto), '');

  -- A categoria escolhida manda no nome. Sem categoria, tenta achar uma pelo
  -- nome digitado; se não houver, o texto original é mantido.
  if new.servico_id is not null
     and (tg_op = 'INSERT' or new.servico_id is distinct from old.servico_id) then
    select * into v_servico from public.lembrete_servicos s where s.id = new.servico_id;
    if found then
      new.servico := v_servico.nome;
    end if;
  elsif nullif(btrim(new.servico), '') is not null
     and (tg_op = 'INSERT' or new.servico is distinct from old.servico) then
    select * into v_servico
    from public.lembrete_servicos s
    where s.nome_normalizado = public.lembrete_normalizar(new.servico);
    if found then
      new.servico_id := v_servico.id;
      new.servico := v_servico.nome;
    else
      new.servico_id := null;
    end if;
  end if;

  -- Sem regra informada: primeira regra ativa que atende o serviço; senão a
  -- primeira regra ativa que atende todos os serviços.
  if new.configuracao_id is null then
    select c.id into new.configuracao_id
    from public.lembrete_configuracoes c
    where c.ativo
      and (
        cardinality(c.servico_ids) = 0
        or (new.servico_id is not null and new.servico_id = any (c.servico_ids))
      )
    order by (cardinality(c.servico_ids) = 0), c.id
    limit 1;
  end if;

  if new.configuracao_id is not null then
    select * into v_cfg
    from public.lembrete_configuracoes c
    where c.id = new.configuracao_id;
  end if;

  if tg_op = 'INSERT'
     or new.configuracao_id is distinct from old.configuracao_id then
    new.configuracao_nome := coalesce(v_cfg.nome, nullif(new.configuracao_nome, ''), 'Sem regra');
  end if;

  -- Atendimento remarcado: sai da mensagem antiga e volta a aguardar o
  -- lembrete da nova data (mesmo que o da data antiga já tenha saído).
  if tg_op = 'UPDATE'
     and new.data_agendada is distinct from old.data_agendada
     and new.status <> 'cancelado' then
    new.status := 'pendente';
    new.mensagem_id := null;
    new.erro := null;
    new.enviado_em := null;
    new.provider_message_id := null;
  end if;

  if new.programado_para is null
     or (
       tg_op = 'UPDATE'
       and (
         new.data_agendada is distinct from old.data_agendada
         or new.configuracao_id is distinct from old.configuracao_id
       )
       and new.programado_para is not distinct from old.programado_para
     ) then
    new.programado_para := (
      (new.data_agendada - coalesce(v_cfg.dias_antecedencia, 1))
      + coalesce(v_cfg.horario_envio, time '18:00')
    ) at time zone coalesce(v_cfg.timezone, 'America/Sao_Paulo');
  end if;

  return new;
end;
$$;

