-- Telefone canônico usado como chave do tutor. Remove o sufixo do WhatsApp e
-- tudo que não for dígito, acrescenta o DDI 55 quando falta e tira o nono
-- dígito de celulares brasileiros, para que 5561993111008 e 556193111008
-- sejam reconhecidos como o mesmo tutor. O envio usa o número original.
create or replace function public.lembrete_telefone_chave(p_telefone text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  with digitos as (
    select regexp_replace(split_part(coalesce(p_telefone, ''), '@', 1), '\D', '', 'g') as d
  ),
  com_ddi as (
    select case when length(d) in (10, 11) then '55' || d else d end as d
    from digitos
  )
  select case
    when length(d) = 13 and left(d, 2) = '55' and substr(d, 5, 1) = '9'
      then left(d, 4) || substr(d, 6)
    else d
  end
  from com_ddi;
$$;

-- Comparação de nomes sem acento e sem diferença de maiúsculas
-- ("vacina" = "Vacina", "Consulta Veterinaria" = "Consulta Veterinária").
create or replace function public.lembrete_normalizar(p_texto text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  select lower(translate(
    btrim(coalesce(p_texto, '')),
    'ÁÀÂÃÄáàâãäÉÈÊËéèêëÍÌÎÏíìîïÓÒÔÕÖóòôõöÚÙÛÜúùûüÇçÑñ',
    'AAAAAaaaaaEEEEeeeeIIIIiiiiOOOOOoooooUUUUuuuuCcNn'
  ));
$$;

