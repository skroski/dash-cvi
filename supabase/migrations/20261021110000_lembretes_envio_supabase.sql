-- Remove as constraints CHECK de uma tabela que citam a coluna informada,
-- qualquer que seja o nome gerado pelo Postgres em produção.
create or replace function public.lembrete_remover_checks(p_tabela regclass, p_coluna text)
returns void
language plpgsql
set search_path = ''
as $$
declare
  v_nome text;
begin
  for v_nome in
    select c.conname
    from pg_catalog.pg_constraint c
    where c.conrelid = p_tabela
      and c.contype = 'c'
      and pg_catalog.pg_get_constraintdef(c.oid) ~ ('\m' || p_coluna || '\M')
  loop
    execute format('alter table %s drop constraint %I', p_tabela, v_nome);
  end loop;
end;
$$;

create or replace function public.set_lembrete_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

