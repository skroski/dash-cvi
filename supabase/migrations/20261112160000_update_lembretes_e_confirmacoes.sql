-- 2. FUNÇÃO: ATUALIZAR CONFIRMAÇÃO (MENSAGEM + AGENDA)
-- ---------------------------------------------------------------------------
create or replace function public.lembrete_atualizar_confirmacao(
  p_mensagem_id bigint,
  p_status text,
  p_resposta text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_msg public.lembrete_mensagens%rowtype;
begin
  perform public.lembretes_exigir_login();

  if p_status not in ('aguardando', 'confirmado', 'cancelado', 'remarcar', 'sem_resposta') then
    raise exception 'Status de confirmação inválido: %', p_status using errcode = 'P0001';
  end if;

  update public.lembrete_mensagens
  set
    status_confirmacao = p_status,
    confirmado_em = case when p_status = 'confirmado' then now() else confirmado_em end,
    resposta_tutor = coalesce(p_resposta, resposta_tutor),
    updated_at = now()
  where id = p_mensagem_id
  returning * into v_msg;

  if not found then
    raise exception 'Mensagem % não encontrada', p_mensagem_id using errcode = 'P0002';
  end if;

  -- Sincroniza o status_agendamento e status em lembrete_envios
  if p_status = 'confirmado' then
    update public.lembrete_envios
    set status_agendamento = 'CONFIRMADO',
        editado_manualmente = true,
        updated_at = now()
    where mensagem_id = p_mensagem_id;
  elsif p_status = 'cancelado' then
    update public.lembrete_envios
    set status_agendamento = 'CANCELADO',
        status = 'cancelado',
        editado_manualmente = true,
        updated_at = now()
    where mensagem_id = p_mensagem_id;
  elsif p_status = 'remarcar' then
    update public.lembrete_envios
    set status_agendamento = 'REMARCAR',
        editado_manualmente = true,
        updated_at = now()
    where mensagem_id = p_mensagem_id;
  elsif p_status = 'aguardando' then
    update public.lembrete_envios
    set status_agendamento = 'AGENDADO',
        editado_manualmente = true,
        updated_at = now()
    where mensagem_id = p_mensagem_id;
  end if;

  -- Registro de evento auditável
  insert into public.lembrete_eventos (mensagem_id, tipo, descricao, dados)
  values (
    p_mensagem_id,
    case when p_status = 'cancelado' then 'cancelado' else 'info' end,
    case p_status
      when 'confirmado' then 'Presença confirmada pelo tutor via WhatsApp.'
      when 'cancelado' then 'Agendamento cancelado pelo tutor via WhatsApp.'
      when 'remarcar' then 'Tutor solicitou remarcação do agendamento.'
      else 'Status de confirmação atualizado no painel.'
    end,
    jsonb_strip_nulls(jsonb_build_object(
      'status_anterior', v_msg.status_confirmacao,
      'status_novo', p_status,
      'resposta_tutor', p_resposta
    ))
  );
end;
$$;

grant execute on function public.lembrete_atualizar_confirmacao(bigint, text, text) to authenticated, anon, service_role;


-- 3. FUNÇÃO: PROCESSAR RESPOSTA DO WHATSAPP (BOTÕES OU TEXTO)
-- ---------------------------------------------------------------------------
create or replace function public.lembrete_processar_resposta_whatsapp(
  p_telefone text,
  p_resposta text default null,
  p_button_id text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_chave text;
  v_msg record;
  v_status text;
  v_btn text;
  v_texto text;
begin
  if p_telefone is null or btrim(p_telefone) = '' then
    return jsonb_build_object('sucesso', false, 'erro', 'Telefone não informado');
  end if;

  v_chave := public.lembrete_telefone_chave(p_telefone);
  v_btn := lower(btrim(coalesce(p_button_id, '')));
  v_texto := public.lembrete_normalizar(coalesce(p_resposta, ''));

  if v_btn in ('confirmar_agendamento', 'confirmar', 'confirm')
     or v_texto in ('confirmar', 'confirmo', 'confirmado', 'sim', 'ok', 'estou confirmado', 'estou confirmando', 'pode confirmar') then
    v_status := 'confirmado';
  elsif v_btn in ('cancelar_agendamento', 'nao_confirmar_agendamento', 'cancelar', 'desmarcar')
     or v_texto in ('cancelar', 'cancelado', 'nao confirmar', 'não confirmar', 'desmarcar', 'cancela', 'nao vou poder', 'não vou poder', 'quero cancelar') then
    v_status := 'cancelado';
  else
    return jsonb_build_object(
      'sucesso', false,
      'erro', 'Resposta não reconhecida como confirmação ou cancelamento',
      'resposta', p_resposta,
      'button_id', p_button_id
    );
  end if;

  -- Para cancelamento, permite cancelar mesmo que já tivesse confirmado anteriormente
  if v_status = 'cancelado' then
    select m.id, m.nome_tutor, m.nome_pet, m.servico, m.data_agendada, m.horario_agendado, m.status_confirmacao
    into v_msg
    from public.lembrete_mensagens m
    where m.telefone_chave = v_chave
      and m.status = 'enviado'
      and m.status_confirmacao <> 'cancelado'
      and m.data_agendada >= (now() at time zone 'America/Sao_Paulo')::date
    order by m.enviado_em desc nulls last, m.id desc
    limit 1;

    if not found then
      select m.id, m.nome_tutor, m.nome_pet, m.servico, m.data_agendada, m.horario_agendado, m.status_confirmacao
      into v_msg
      from public.lembrete_mensagens m
      where m.telefone_chave = v_chave
        and m.status = 'enviado'
        and m.status_confirmacao <> 'cancelado'
      order by m.enviado_em desc nulls last, m.id desc
      limit 1;
    end if;
  else
    -- Para confirmação, busca prioritariamente quem estava aguardando
    select m.id, m.nome_tutor, m.nome_pet, m.servico, m.data_agendada, m.horario_agendado, m.status_confirmacao
    into v_msg
    from public.lembrete_mensagens m
    where m.telefone_chave = v_chave
      and m.status = 'enviado'
      and m.status_confirmacao in ('aguardando', 'remarcar')
    order by m.enviado_em desc nulls last, m.id desc
    limit 1;

    if not found then
      select m.id, m.nome_tutor, m.nome_pet, m.servico, m.data_agendada, m.horario_agendado, m.status_confirmacao
      into v_msg
      from public.lembrete_mensagens m
      where m.telefone_chave = v_chave
        and m.status = 'enviado'
        and m.enviado_em >= (now() - interval '3 days')
      order by m.enviado_em desc nulls last, m.id desc
      limit 1;
    end if;
  end if;

  if not found then
    return jsonb_build_object(
      'sucesso', false,
      'erro', 'Nenhum lembrete recente encontrado para este telefone',
      'telefone_chave', v_chave
    );
  end if;

  perform public.lembrete_atualizar_confirmacao(
    v_msg.id,
    v_status,
    coalesce(p_resposta, case when v_status = 'confirmado' then 'Botão: Confirmar' else 'Botão: Cancelar' end)
  );

  return jsonb_build_object(
    'sucesso', true,
    'mensagem_id', v_msg.id,
    'status_confirmacao', v_status,
    'nome_tutor', v_msg.nome_tutor,
    'nome_pet', v_msg.nome_pet,
    'servico', v_msg.servico,
    'data_agendada', v_msg.data_agendada,
    'horario_agendado', v_msg.horario_agendado
  );
end;
$$;

grant execute on function public.lembrete_processar_resposta_whatsapp(text, text, text) to authenticated, anon, service_role;


-- 4. FUNÇÃO: ENVIAR AGENDAMENTO INDIVIDUAL ("Enviar lembrete agora")
-- ---------------------------------------------------------------------------
create or replace function public.lembretes_enviar_agendamento(p_envio_id bigint)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_envio public.lembrete_envios%rowtype;
  v_cfg public.lembrete_configuracoes%rowtype;
  v_hoje date;
  v_mensagem_id bigint;
begin
  perform public.lembretes_exigir_login();

  select * into v_envio
  from public.lembrete_envios e
  where e.id = p_envio_id;
  if not found then
    raise exception 'Agendamento não encontrado.' using errcode = 'P0002';
  end if;
  if v_envio.configuracao_id is null then
    raise exception 'Escolha uma regra para este agendamento antes de enviar.' using errcode = 'P0001';
  end if;
  if v_envio.status not in ('pendente', 'falha', 'ignorado') then
    raise exception 'Este agendamento não está aguardando lembrete.' using errcode = 'P0001';
  end if;

  select * into v_cfg
  from public.lembrete_configuracoes c
  where c.id = v_envio.configuracao_id;

  v_hoje := (now() at time zone coalesce(v_cfg.timezone, 'America/Sao_Paulo'))::date;
  if v_envio.data_agendada < v_hoje then
    raise exception 'A data deste agendamento já passou.' using errcode = 'P0001';
  end if;

  -- Trava diária por pet (só bloqueia se já foi efetivamente enviado ou está enviando agora)
  if exists (
    select 1 from public.lembrete_mensagens m
    where m.telefone_chave = v_envio.telefone_chave
      and m.dia_envio = v_hoje
      and lower(btrim(coalesce(m.nome_pet, (m.nomes_pets)[1], ''))) = lower(btrim(coalesce(v_envio.nome_pet, '')))
      and m.disparo <> 'teste'
      and m.status in ('enviado', 'processando')
  ) then
    raise exception 'Este pet já recebeu um lembrete hoje (limite de 1 por pet por dia).' using errcode = 'P0001';
  end if;

  -- Se já existe mensagem vinculada na fila (ou com falha/ignorada), coloca para sair AGORA (now())
  if v_envio.mensagem_id is not null then
    update public.lembrete_mensagens m
    set
      status = 'pendente',
      disparo = 'manual',
      programado_para = now(),
      processando_desde = null,
      erro = null,
      configuracao_id = coalesce(v_cfg.id, m.configuracao_id),
      configuracao_nome = coalesce(v_cfg.nome, m.configuracao_nome),
      categoria = coalesce(v_cfg.categoria, m.categoria, 'consulta'),
      botoes_confirmacao = coalesce(v_cfg.botoes_confirmacao, m.botoes_confirmacao, true),
      pausa_ia_minutos = coalesce(v_cfg.pausa_ia_minutos, m.pausa_ia_minutos, 1.5),
      updated_at = now()
    where m.id = v_envio.mensagem_id
      and m.status in ('pendente', 'falha', 'ignorado', 'cancelado');

    if found then
      update public.lembrete_envios e
      set status = 'pendente', erro = null, updated_at = now()
      where e.id = v_envio.id;

      return v_envio.mensagem_id;
    end if;
  end if;

  update public.lembrete_envios e
  set status = 'pendente', erro = null, mensagem_id = null
  where e.id = v_envio.id;

  perform public.lembrete_enfileirar(
    v_envio.configuracao_id,
    v_envio.data_agendada,
    now(),
    'manual',
    v_envio.telefone_chave
  );

  select e.mensagem_id into v_mensagem_id
  from public.lembrete_envios e
  where e.id = v_envio.id;

  if v_mensagem_id is not null then
    update public.lembrete_mensagens m
    set
      status = 'pendente',
      disparo = 'manual',
      programado_para = now(),
      processando_desde = null,
      erro = null,
      configuracao_id = coalesce(v_cfg.id, m.configuracao_id),
      configuracao_nome = coalesce(v_cfg.nome, m.configuracao_nome),
      categoria = coalesce(v_cfg.categoria, m.categoria, 'consulta'),
      botoes_confirmacao = coalesce(v_cfg.botoes_confirmacao, m.botoes_confirmacao, true),
      pausa_ia_minutos = coalesce(v_cfg.pausa_ia_minutos, m.pausa_ia_minutos, 1.5),
      updated_at = now()
    where m.id = v_mensagem_id
      and m.status = 'pendente';
  end if;

  return v_mensagem_id;
end;
$$;

grant execute on function public.lembretes_enviar_agendamento(bigint) to authenticated, anon, service_role;


-- 5. FUNÇÃO: MARCAR COMO ENVIADO APÓS DISPARO MANUAL DIRETO
-- ---------------------------------------------------------------------------
create or replace function public.lembrete_marcar_enviado_manual(
  p_mensagem_id bigint,
  p_texto text default null,
  p_provider_message_id text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_msg public.lembrete_mensagens%rowtype;
begin
  perform public.lembretes_exigir_login();

  update public.lembrete_mensagens m
  set
    status = 'enviado',
    disparo = case when m.disparo = 'teste' then 'teste' else 'manual' end,
    texto = coalesce(nullif(btrim(p_texto), ''), m.texto),
    origem_texto = 'manual',
    enviado_em = coalesce(m.enviado_em, now()),
    provider_message_id = coalesce(nullif(btrim(p_provider_message_id), ''), m.provider_message_id),
    tentativas = greatest(m.tentativas, 1),
    processando_desde = null,
    erro = null,
    updated_at = now()
  where m.id = p_mensagem_id
  returning * into v_msg;

  if not found then
    raise exception 'Mensagem % não encontrada.', p_mensagem_id using errcode = 'P0002';
  end if;

  update public.lembrete_envios e
  set
    status = 'enviado',
    enviado_em = coalesce(v_msg.enviado_em, now()),
    provider_message_id = coalesce(v_msg.provider_message_id, e.provider_message_id),
    tentativas = greatest(e.tentativas, 1),
    erro = null,
    updated_at = now()
  where e.mensagem_id = p_mensagem_id
    and e.status <> 'cancelado';
end;
$$;

grant execute on function public.lembrete_marcar_enviado_manual(bigint, text, text) to authenticated, anon, service_role;


-- 6. FUNÇÃO: DESTRAVAR FILA EMPACADA E ATUALIZAR AGENDAMENTOS
-- ---------------------------------------------------------------------------
create or replace function public.lembretes_destravar_fila_pendente(
  p_data_alvo date default null,
  p_configuracao_id bigint default null
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_msg record;
  v_slot timestamptz := now();
  v_min smallint;
  v_max smallint;
  v_destravadas integer := 0;
begin
  for v_msg in
    select
      m.id,
      m.configuracao_id,
      coalesce(c.intervalo_min_segundos, 20) as min_sec,
      coalesce(c.intervalo_max_segundos, 45) as max_sec
    from public.lembrete_mensagens m
    left join public.lembrete_configuracoes c on c.id = m.configuracao_id
    where m.status = 'pendente'
      and m.disparo <> 'teste'
      and (p_data_alvo is null or m.data_agendada = p_data_alvo)
      and (p_configuracao_id is null or m.configuracao_id = p_configuracao_id)
    order by m.programado_para asc, m.id asc
    for update of m skip locked
  loop
    v_min := coalesce(v_msg.min_sec, 20);
    v_max := greatest(coalesce(v_msg.max_sec, 45), v_min);

    update public.lembrete_mensagens
    set
      disparo = 'manual',
      programado_para = v_slot,
      processando_desde = null,
      erro = null,
      updated_at = now()
    where id = v_msg.id;

    v_destravadas := v_destravadas + 1;
    v_slot := v_slot + make_interval(secs => v_min + floor(random() * (v_max - v_min + 1)));
  end loop;

  return v_destravadas;
end;
$$;

grant execute on function public.lembretes_destravar_fila_pendente(date, bigint) to authenticated, anon, service_role;

